import { test,expect } from '@playwright/test'
import fs from 'node:fs/promises'
import path from 'node:path'
import os from 'node:os'
import type { fountainBenchProbe } from './fountainBenchProbe'

test('fountain approaches are sloped and the reference ring bench supports both local seats and safe exits',async({page})=>{
  await page.setViewportSize({width:1280,height:720})
  const errors:string[]=[],network:string[]=[]
  page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())})
  page.on('request',r=>{if(/\/api\/|\/ws\/|\.glb/.test(r.url()))network.push(r.url())})
  await page.goto('/layout-preview.html')
  await expect(page.getByText('배치 준비 완료',{exact:true})).toBeVisible({timeout:90000})
  const probe=():Promise<ReturnType<typeof fountainBenchProbe>>=>page.evaluate(async()=>(await import('/tests/layout-e2e/fountainBenchProbe.ts' as string)).fountainBenchProbe())
  const dir=process.env.QA_ARTIFACT_DIR??path.join(os.tmpdir(),'ontop-layout-qa')
  await fs.mkdir(dir,{recursive:true})
  const shot=(name:string)=>page.screenshot({path:path.join(dir,name+'.png')})
  await page.getByLabel('배치 시안 시설 목록').getByRole('button',{name:/06.*분수/}).click()
  await page.waitForTimeout(600);await shot('fountain-continuous-slope')
  await page.getByLabel('배치 시안 시설 목록').getByRole('button',{name:/05.*운동마당/}).click()
  await page.waitForTimeout(500);await shot('fitness-ring-bench')
  expect((await probe()).treeShared).toBe(true)
  await page.getByRole('button',{name:'원형 벤치 체험',exact:true}).click()
  const hud=page.getByRole('region',{name:'원형 벤치 이용'})
  await expect(hud).toBeVisible()
  await hud.getByRole('button',{name:'1번 좌석에 앉기',exact:true}).click()
  await expect(hud).toContainText('원형 벤치에 앉아 있어요')
  await expect.poll(async()=>(await probe()).seated?.seatIndex).toBe(0)
  const seated=await probe()
  expect(seated.position).toEqual([seated.seat!.x,seated.seat!.z])
  expect(seated.camera[1]).toBeCloseTo(1.35)
  await page.keyboard.down('w');await page.waitForTimeout(350);await page.keyboard.up('w')
  expect((await probe()).position).toEqual(seated.position)
  await shot('fitness-ring-bench-seated')
  await page.keyboard.press('KeyE')
  await expect(hud.getByRole('button',{name:'2번 좌석에 앉기',exact:true})).toBeVisible()
  expect((await probe()).position).toEqual([seated.exit!.x,seated.exit!.z])
  expect((await probe()).walkable).toBe(true)
  await hud.getByRole('button',{name:'2번 좌석에 앉기',exact:true}).click()
  await expect.poll(async()=>(await probe()).seated?.seatIndex).toBe(1)
  await hud.getByRole('button',{name:/벤치에서 일어나기/}).click()
  await expect.poll(async()=>(await probe()).seated).toBeNull()
  expect((await probe()).walkable).toBe(true)
  await page.setViewportSize({width:390,height:844})
  await expect(hud).toBeVisible()
  const box=await hud.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0);expect(box!.x+box!.width).toBeLessThanOrEqual(390)
  await shot('fitness-ring-bench-mobile')
  expect(errors).toEqual([]);expect(network).toEqual([])
})
