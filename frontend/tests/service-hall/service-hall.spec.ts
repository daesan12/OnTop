import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import path from 'node:path'

const evidence = process.env.SKEWER_HALL_EVIDENCE
const runtimeErrors = new WeakMap<Page, string[]>()
test.beforeEach(({ page }) => {
  const errors: string[] = []; runtimeErrors.set(page, errors)
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
})
test.afterEach(({ page }) => { expect(runtimeErrors.get(page)).toEqual([]) })
async function capture(page: Page, name: string) {
  if (!evidence) return
  await mkdir(evidence, { recursive: true })
  await page.screenshot({ path: path.join(evidence, `${name}.png`), animations: 'disabled' })
}
async function open(page: Page) {
  await page.goto('/skewer-service-hall.html')
  await expect(page.locator('.service-stage')).toHaveAttribute('data-ready', 'true', { timeout: 45000 })
  await expect(page.getByRole('alert')).toHaveCount(0)
}
// Wait for the actual projected player anchor to stop, rather than jumping the model to a fixture position.
async function walk(page: Page, name: string, action: RegExp) {
  await page.getByRole('button', { name, exact: true }).click()
  await expect(page.locator('.service-action')).toHaveAccessibleName(action, { timeout: 18000 })
  let last = '', stable = 0
  await expect.poll(async () => {
    const current = await page.locator('.service-stage').evaluate(el => `${(el as HTMLElement).style.getPropertyValue('--hall-action-x')}:${(el as HTMLElement).style.getPropertyValue('--hall-action-y')}`)
    stable = current === last ? stable + 1 : 0; last = current
    return stable
  }, { timeout: 18000, intervals: [200] }).toBeGreaterThanOrEqual(2)
}
const table = (page: Page, id: number) => page.locator(`[data-table="${id}"]`)

