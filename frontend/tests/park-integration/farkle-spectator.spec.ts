import { expect, test } from '@playwright/test'
import { fixture, screenshot } from '../e2e/contractFixture'

test('DICE spectators see a close readable board, confirmed scores and accessible observer controls', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  const server = await fixture(page, { generatedPark: true, omok: true, dice: true, publicSpectator: true, ownUserId: '505', spectatorEvents: true,
    publicProfiles: { '101': { nickname: '가람', characterGender: 'MALE' }, '102': { nickname: '솔바람', characterGender: 'FEMALE' } } })
  await page.goto('/park'); await expect(page).toHaveTitle('OnTop')
  await expect.poll(() => page.evaluate(async () => (await import('/tests/park-integration/probe.ts' as string)).sceneReady()), { timeout: 90000 }).toBe(true)
  await page.getByRole('button', { name: 'E 관전하기', exact: true }).click()
  const hud = page.getByRole('region', { name: '주사위 경기', exact: true })
  const details = hud.locator('.farkle-spectator'), scorebar = hud.locator('.farkle-observer-scorebar')
  const tray = () => page.evaluate(async () => (await import('/tests/park-integration/farkleSpectatorProbe.ts' as string)).spectatorTrayBounds())
  const ready = () => expect.poll(() => page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).farkleProbe().cameraReady)).toBe(true)
  await expect(hud).toBeVisible()
  server.diceSnapshot({ scores: [2200, 2750], turnScore: 1000, round: 7, turnUserId: '101', turnDeadline: new Date(Date.now() + 30000).toISOString(),
    dice: [1, 1, 1, 5, 3, 6].map((value, id) => ({ id, value, held: id < 3 })), stage: 'SELECTING', rollId: 3, lastEvent: 'ROLL' }, 'SPECTATOR')
  await expect(hud).toHaveAttribute('data-rolling', 'false'); await ready()
  await expect(scorebar.getByLabel('가람 저장 점수', { exact: true })).toContainText('2,200')
  await expect(scorebar.getByLabel('솔바람 저장 점수', { exact: true })).toContainText('2,750')
  await expect(scorebar.getByLabel('가람 저장 점수', { exact: true })).toContainText('차례')
  expect((await tray()).width).toBeGreaterThan(650)
  await expect(page.getByRole('complementary', { name: '조작 방법', exact: true })).toBeHidden()
  await expect(page.getByRole('button', { name: '공원 지도', exact: true })).toBeHidden()
  await screenshot(page, 'spectator-focus-desktop')
  await details.locator('summary').focus(); await page.keyboard.press('Tab')
  await expect(hud).toHaveAttribute('data-view', 'board'); await expect(details.locator(':focus')).toHaveCount(1)
  await page.keyboard.press('KeyR'); await page.keyboard.press('KeyQ'); await page.keyboard.press('KeyT')
  await expect(page.getByRole('dialog', { name: '주사위 점수표', exact: true })).toBeHidden()
  expect(server.sent.filter(m => m.type === 'GAME_ACTION_SEND' || m.type === 'GAME_FORFEIT')).toHaveLength(0)
  const checks = server.sent.filter(m => m.type === 'GAME_STATE_CHECK').length
  await details.getByRole('button', { name: '상태 새로고침', exact: true }).click()
  await expect.poll(() => server.sent.filter(m => m.type === 'GAME_STATE_CHECK').length).toBe(checks + 1)
  await details.getByRole('button', { name: '게임 설명', exact: true }).click()
  const manual = page.getByRole('dialog', { name: '게임 설명서', exact: true })
  await expect(manual).toHaveAttribute('data-phase', 'open'); await page.keyboard.press('Escape'); await expect(manual).toBeHidden()
  await expect(hud).toBeVisible()
  server.diceSnapshot({ scores: [3250, 2750], turnScore: 0, round: 8, turnUserId: '102', dice: [], stage: 'AWAITING_ROLL', lastEvent: 'BANK' }, 'SPECTATOR')
  await expect(scorebar.getByLabel('가람 저장 점수', { exact: true })).toContainText('3,250')
  await expect(scorebar.getByLabel('솔바람 저장 점수', { exact: true })).toContainText('차례')
  await expect(scorebar.getByLabel('가람 저장 점수', { exact: true })).not.toContainText('차례')
  server.profile('101', { nickname: '아주 긴 이름을 가진 주사위 참가자', characterGender: 'MALE' })
  for (const size of [{ width: 1366, height: 768 }, { width: 390, height: 844 }, { width: 320, height: 568 }, { width: 844, height: 390 }]) {
    await page.setViewportSize(size); await ready()
    await expect(scorebar).toBeInViewport({ ratio: 1 })
    const box = await tray(), scores = await scorebar.boundingBox()
    expect(box.left).toBeGreaterThanOrEqual(0); expect(box.right).toBeLessThanOrEqual(size.width)
    expect(box.top).toBeGreaterThan(scores!.y + scores!.height)
    const chat = await page.getByRole('region', { name: '경기 채팅', exact: true }).boundingBox()
    expect(box.right <= chat!.x || box.left >= chat!.x + chat!.width || box.bottom <= chat!.y || box.top >= chat!.y + chat!.height, JSON.stringify({size,box,chat})).toBe(true)
    await screenshot(page, 'spectator-focus-' + size.width + 'x' + size.height)
    if (!await details.evaluate(node => (node as HTMLDetailsElement).open)) await details.locator('summary').click()
    const exit = details.getByRole('button', { name: '관전 종료', exact: true })
    await exit.scrollIntoViewIfNeeded(); await expect(exit).toBeInViewport({ ratio: 1 })
    await details.getByText('관전자는 주사위를 선택하거나 굴릴 수 없습니다.', { exact: true }).scrollIntoViewIfNeeded()
    expect(await details.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    await details.locator('summary').scrollIntoViewIfNeeded(); await details.locator('summary').click()
  }
  await page.setViewportSize({ width: 1920, height: 1080 })
  if (!await details.evaluate(node => (node as HTMLDetailsElement).open)) await details.locator('summary').click()
  await details.getByRole('button', { name: '테이블 둘러보기', exact: true }).click()
  await expect(hud).toHaveAttribute('data-view', 'table')
  await details.getByRole('button', { name: '공개 판 보기', exact: true }).click(); await ready()
  await details.getByRole('button', { name: '관전 종료', exact: true }).click(); await expect(hud).toBeHidden()
  await expect(page.getByRole('button', { name: '공원 지도', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'E 관전하기', exact: true }).click(); await expect(hud).toBeVisible()
  // The shared watcher releases a terminal match; it owns the park-return lifecycle.
  server.diceSnapshot({ status: 'FINISHED', stage: 'FINISHED', scores: [4100, 2750], winnerUserId: '101', turnUserId: null, turnDeadline: null, endReason: 'TARGET_REACHED', endedAt: new Date().toISOString() }, 'SPECTATOR')
  await expect(hud).toBeHidden(); await expect(page.getByRole('button', { name: '공원 지도', exact: true })).toBeVisible()
  expect(server.sent.filter(m => m.type === 'GAME_ACTION_SEND' || m.type === 'GAME_FORFEIT')).toHaveLength(0)
  await expect(page.locator('vite-error-overlay')).toHaveCount(0); expect(errors).toEqual([])
})
