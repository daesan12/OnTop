test('closing while a purchase is pending keeps its identity, ignores late UI completion and never auto-repeats the debit', async ({ page }) => {
  const server = await fixture(page)
  const rest = await shopFixture(page, equipment => server.equipment('101', equipment))
  await loaded(page); rest.purchaseMode('hold'); await choose(page)
  await dialog(page).getByRole('button', { name: '구매 확정', exact: true }).click()
  await expect.poll(() => rest.debitCount).toBe(1)
  await dialog(page).getByRole('button', { name: '상점 닫기' }).click()
  await rest.release()
  await page.getByRole('button', { name: '상점·보유 아이템 열기' }).click()
  await expect(dialog(page).getByRole('button', { name: '같은 구매 다시 확인', exact: true })).toBeEnabled()
  expect(rest.calls.filter(c => c.method === 'POST')).toHaveLength(1)
  await dialog(page).getByRole('button', { name: '같은 구매 다시 확인', exact: true }).click()
  await expect(dialog(page).getByLabel('구매 영수증')).toBeVisible()
  expect(rest.debitCount).toBe(1)
  const calls = rest.calls.filter(c => c.method === 'POST'); expect(calls[0]).toEqual(calls[1])
})

