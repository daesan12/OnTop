import { expect, test, type Page } from '@playwright/test'
import { fixture, screenshot } from './contractFixture'
import { feedbackFixture } from './feedbackFixture'
import { MAILBOX } from '../../src/config'
const near = { x: MAILBOX.x - 1.5, y: 0.8, z: MAILBOX.z, yaw: 0 }
const body = '공원 산책로 안내를 늘려주세요. 고맙습니다.'
const dialog = (p: Page) => p.getByRole('dialog', { name: '온탑 소리함' })
const area = (p: Page) => dialog(p).getByLabel('의견 내용')
const probe = (p: Page): Promise<ReturnType<typeof import('./sceneProbe').feedbackProbe>> =>
  p.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).feedbackProbe())
async function open(p: Page) {
  await p.getByLabel('가까운 상호작용').getByRole('button', { name: /소리함에 의견 쓰기/ }).click()
  await expect(dialog(p)).toBeVisible(); await expect(area(p)).toBeFocused()
}
async function loaded(p: Page) {
  await p.goto('/park'); await expect(p).toHaveTitle('OnTop')
  await expect(p.getByLabel('공원 기본 화면')).toBeVisible()
  await expect(p.getByText('공원을 준비하고 있어요…')).toBeHidden({ timeout: 90_000 })
  await p.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).orbit(0, 0.35, 6.8))
  await open(p)
}
test('M07 sends private authenticated REST and retains text until its receipt, then restores input', async ({ page }) => {
  const errors: string[] = [], consoleErrors: string[] = [], admin: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('console', m => { if (m.type() === 'error') consoleErrors.push(m.text()) })
  page.on('request', r => { if (new URL(r.url()).pathname.startsWith('/api/v1/admin/')) admin.push(r.url()) })
  const server = await fixture(page, { manualMovement: true, position: near })
  const rest = await feedbackFixture(page); rest.mode('hold')
  await loaded(page)
  const raw = '  ' + body + '\u200b\n'
  await area(page).fill(raw)
  await page.keyboard.press('KeyG')
  await expect(page.getByRole('dialog', { name: '감정표현 선택' })).toBeHidden()
  await area(page).fill(raw)
  await dialog(page).getByRole('button', { name: '의견 보내기', exact: true }).click()
  await expect.poll(() => rest.acceptedCount).toBe(1)
  await expect(area(page)).toHaveValue(raw)
  await expect(area(page)).toHaveJSProperty('readOnly', true)
  await expect(dialog(page).getByRole('button', { name: '전달 중…', exact: true })).toBeDisabled()
  expect(rest.requests).toHaveLength(1)
  expect(rest.requests[0]).toMatchObject({ channelId: 'fixture-channel', text: body })
  expect(JSON.stringify(server.sent)).not.toContain(body)
  expect((await probe(page)).publicData).not.toContain(body)
  await rest.release()
  await expect(dialog(page)).toContainText('의견을 전달했어요. 고맙습니다!')
  await expect(area(page)).toHaveValue('')
  await expect(dialog(page).getByRole('button', { name: /초 후 보내기/ })).toBeDisabled()
  await screenshot(page, 'm07-rest-approved')
  await page.keyboard.press('Escape'); await expect(dialog(page)).toBeHidden()
  await page.keyboard.down('KeyW')
  await expect.poll(() => server.sent.some(m => m.type === 'WORLD_MOVE' && (m.payload.dx || m.payload.dz))).toBe(true)
  await page.keyboard.up('KeyW')
  expect(admin).toEqual([])
  expect(await page.locator('vite-error-overlay').count()).toBe(0)
  expect(errors).toEqual([]); expect(consoleErrors).toEqual([])
})
test('M07 recovers an accepted but lost response using the original operation and payload', async ({ page }) => {
  await fixture(page, { manualMovement: true, position: near })
  const rest = await feedbackFixture(page); rest.mode('acceptThenLose')
  await loaded(page); await area(page).fill(body)
  await dialog(page).getByRole('button', { name: '의견 보내기', exact: true }).click()
  await expect(dialog(page).getByRole('alert')).toContainText('전달 결과를 확인하지 못했습니다')
  await expect(area(page)).toHaveValue(body)
  const original = { ...rest.requests[0]! }
  expect(rest.acceptedCount).toBe(1)
  await page.keyboard.press('Escape'); await open(page)
  rest.mode('outOfRange')
  await dialog(page).getByRole('button', { name: '같은 의견 다시 보내기', exact: true }).click()
  await expect(dialog(page)).toContainText('의견을 전달했어요')
  await expect(area(page)).toHaveValue('')
  expect(rest.requests).toEqual([original, original]); expect(rest.acceptedCount).toBe(1)
})
test('M07 keeps login on business 403 and respects the server cooldown on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const server = await fixture(page, { manualMovement: true, position: near })
  const rest = await feedbackFixture(page); rest.mode('outOfRange')
  await loaded(page); await area(page).fill(body)
  await dialog(page).getByRole('button', { name: '의견 보내기', exact: true }).click()
  await expect(dialog(page).getByRole('alert')).toContainText('소리함 가까이')
  await expect(area(page)).toHaveValue(body)
  expect(page.url()).toContain('/park'); expect(server.connections).toBe(1)
  rest.mode('cooldown')
  await dialog(page).getByRole('button', { name: '같은 의견 다시 보내기', exact: true }).click()
  await expect(dialog(page).getByRole('alert')).toContainText('잠시 후')
  await expect(dialog(page).getByRole('button', { name: /초 후 보내기/ })).toBeDisabled()
  expect((await probe(page)).nextAllowedAt).toBe(Date.parse(rest.deadline))
  expect(new Set(rest.requests.map(r => r.operationId)).size).toBe(1)
  expect(rest.acceptedCount).toBe(0)
  await screenshot(page, 'm07-rest-mobile-cooldown')
})
