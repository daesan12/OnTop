import { expect, test, type Page } from '@playwright/test'
import { fixture, screenshot } from './contractFixture'
import { FITNESS_STATIONS } from '../../src/config'
import { fitnessAnchors } from '../../src/features/fitness/anchors'

async function probe(page: Page, id: string): Promise<ReturnType<typeof import('./sceneProbe').fitnessProbe>> {
  return page.evaluate(async id => (await import('/tests/e2e/sceneProbe.ts' as string)).fitnessProbe(id), id)
}
async function loaded(page: Page) {
  await page.goto('/park')
  await expect(page).toHaveTitle('OnTop')
  await expect(page.getByLabel('공원 기본 화면')).toBeVisible()
  await expect(page.getByText('공원을 준비하고 있어요…')).toBeHidden({ timeout: 90_000 })
  await page.locator('canvas').focus()
}
const hint = (page: Page) => page.getByLabel('가까운 상호작용')

test('M05 enters/leaves all 12 machines, retaining distinct mechanisms on the shared approved clock', async ({ page }) => {
  const errors: string[] = [], consoleErrors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') consoleErrors.push(message.text()) })
  const server = await fixture(page, { manualMovement: true, position: fitnessAnchors(FITNESS_STATIONS[0]!.id).exit })
  await loaded(page)
  server.remotePose({ x: 0, y: 0.8, z: 34 })
  await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).fixtureProfiles())
  for (const station of FITNESS_STATIONS) {
    const approach = fitnessAnchors(station.id).exit
    server.pose(approach)
    await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).orbit(0, 0.35, 5.2))
    await expect(hint(page)).toHaveAttribute('data-fitness-id', station.id)
    await expect(hint(page).getByRole('button', { name: new RegExp(station.name + ' 이용하기') })).toBeEnabled()
    await page.locator('canvas').focus()
    await page.keyboard.press('KeyE')
    await expect(hint(page)).toContainText('이용 중')
    await expect(hint(page).getByRole('button', { name: '운동기구에서 내려오기' })).toHaveCount(0)
    await expect(hint(page)).not.toContainText('서버가 점유와 운동 시작 시각을 동기화합니다.')
    await expect(hint(page)).toContainText('목업')
    await expect.poll(async () => (await probe(page, station.id)).fitnessId).toBe(station.id)
    const active = await probe(page, station.id)
    expect(active.avatarStartedAt).toBe(active.lease!.startedAt)
    expect(active.authoritative).toEqual(approach)
    expect(active.displayed).toEqual(fitnessAnchors(station.id).use)
    expect(active.ownVisible).toBe(true)
    // Small tolerance for the elapsed time between a render frame and this sample.
    await expect.poll(async () => (await probe(page, station.id)).machineError).toBeLessThan(0.18)
    await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).orbit(Math.PI / 2, 0.35, 5.2))
    await page.waitForTimeout(500)
    await screenshot(page, 'm05-' + station.id)
    await page.locator('canvas').focus(); await page.keyboard.press('KeyW')
    await expect.poll(async () => (await probe(page, station.id)).fitnessId).toBe('')
    await expect.poll(async () => (await probe(page, station.id)).machineError).toBeLessThan(0.001)
    expect((await probe(page, station.id)).displayed).toEqual(approach)
  }
  expect(server.sent.some(message => /FITNESS|use-fitness|leave-fitness/.test(message.type))).toBe(false)
  expect(await page.locator('vite-error-overlay').count()).toBe(0)
  expect(errors).toEqual([])
  expect(consoleErrors).toEqual([])
})

test('M05 shows remote occupancy, clears departed leases, keeps chat/G input isolated and resumes WASD after release', async ({ page }) => {
  const station = FITNESS_STATIONS[0]!
  const server = await fixture(page, { manualMovement: true, position: fitnessAnchors(station.id).exit })
  await loaded(page)
  await page.evaluate(async id => (await import('/tests/e2e/sceneProbe.ts' as string)).fixtureFitness('102', id), station.id)
  await expect(hint(page)).toContainText('산책자 102 님이 사용 중')
  await expect(hint(page).getByRole('button')).toBeDisabled()
  await page.locator('canvas').focus()
  await page.keyboard.press('KeyE')
  expect((await probe(page, station.id)).fitnessId).toBe('')
  expect((await probe(page, station.id)).remoteVisible).toBe(true)
  const remote = await probe(page, station.id)
  expect(remote.occupantStartedAt).toBe(remote.lease!.startedAt)
  expect(remote.occupantFitnessId).toBe(station.id)
  await expect.poll(async () => (await probe(page, station.id)).machineError).toBeLessThan(0.18)
  server.players(1)
  await expect(hint(page).getByRole('button')).toBeEnabled()
  await page.keyboard.press('KeyE')
  await expect(hint(page)).toContainText('이용 중')
  await expect(hint(page).getByRole('button', { name: '운동기구에서 내려오기' })).toHaveCount(0)
  await expect(hint(page)).not.toContainText('서버가 점유와 운동 시작 시각을 동기화합니다.')
  await page.keyboard.press('Enter')
  await page.getByLabel('주변 채팅 메시지').fill('운동하며 대화')
  await page.keyboard.press('KeyW')
  expect((await probe(page, station.id)).fitnessId).toBe(station.id)
  await page.keyboard.press('Escape')
  await page.locator('canvas').focus()
  await page.keyboard.press('Shift+Space')
  expect((await probe(page, station.id)).fitnessId).toBe(station.id)
  expect(server.sent.filter(m => m.type === 'WORLD_MOVE' && m.payload.jump)).toHaveLength(0)
  await page.getByRole('button', { name: '감정표현 열기' }).click()
  await expect(page.getByRole('dialog', { name: '감정표현 선택' }).getByRole('button', { name: '박수', exact: true })).toBeDisabled()
  await page.keyboard.press('KeyW')
  expect((await probe(page, station.id)).fitnessId).toBe(station.id)
  await page.keyboard.press('Escape')
  await page.locator('canvas').focus()
  await page.keyboard.down('KeyW')
  await expect.poll(async () => (await probe(page, station.id)).fitnessId).toBe('')
  await expect.poll(() => server.sent.some(m => m.type === 'WORLD_MOVE' && (m.payload.dx || m.payload.dz))).toBe(true)
  await page.keyboard.up('KeyW')
  await expect(hint(page)).toHaveAttribute('data-fitness-id', station.id)
  await page.keyboard.press('KeyE')
  await expect.poll(async () => (await probe(page, station.id)).fitnessId).toBe(station.id)
  server.close(1012)
  await expect.poll(() => server.connections, { timeout: 15_000 }).toBe(2)
  await expect.poll(async () => (await probe(page, station.id)).fitnessId).toBe('')
  await expect.poll(async () => Object.keys((await probe(page, station.id)).placements).length).toBe(0)
  await expect.poll(async () => (await probe(page, station.id)).machineError).toBeLessThan(0.001)
  expect(server.maxActive).toBe(1)
})

test('M05 keeps the exercise hint readable and exits with movement in a narrow viewport', async ({ page }) => {
  const station = FITNESS_STATIONS[0]!
  await fixture(page, { manualMovement: true, position: fitnessAnchors(station.id).exit })
  await loaded(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(hint(page)).toHaveAttribute('data-fitness-id', station.id)
  await hint(page).getByRole('button').click()
  await expect(hint(page)).toContainText('이용 중')
  await expect(hint(page).getByRole('button', { name: '운동기구에서 내려오기' })).toHaveCount(0)
  const box = await hint(page).boundingBox()
  const emote = await page.getByRole('button', { name: '감정표현 열기' }).boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(390)
  expect(emote!.y + emote!.height).toBeLessThan(box!.y)
  await screenshot(page, 'm05-mobile')
  await page.locator('canvas').focus(); await page.keyboard.press('KeyW')
  await expect.poll(async () => (await probe(page, station.id)).fitnessId).toBe('')
})
