test('M11 BUST/timeouts stay server-owned; stale rejection requires refresh, recovery does not extend the deadline', async ({ page }) => {
  const server = await start(page)
  server.rejectNextAction('GAME_ACTION_STALE_VERSION', '최신 주사위 판을 확인해주세요.')
  await roll(page).click(); await expect(panel(page)).toContainText('반영 여부를 확인해야 합니다.')
  await expect(roll(page)).toBeDisabled()
  await panel(page).getByRole('button', { name: '최신 주사위 확인' }).click(); await expect(roll(page)).toBeEnabled()
  server.dropActions(true)
  await roll(page).click(); await expect(roll(page)).toBeDisabled()
  await page.keyboard.press('KeyR')
  await expect(panel(page)).toContainText('응답 시간이 초과되었습니다.', { timeout: 12000 })
  server.dropActions(false)
  await panel(page).getByRole('button', { name: '최신 주사위 확인' }).click(); await expect(roll(page)).toBeEnabled()
  server.diceSnapshot({ lastEvent: 'BUST', turnUserId: '102', round: 2, turnScore: 0 })
  await expect(panel(page)).toContainText('BUST'); await expect(roll(page)).toBeDisabled()
  server.diceSnapshot({ lastEvent: 'TURN_TIMEOUT', turnUserId: '101', round: 3 })
  await expect(roll(page)).toBeEnabled()
  server.recoveryPending(); await expect(roll(page)).toBeDisabled()
  server.restoreGame(); await expect(roll(page)).toBeEnabled()
  server.diceSnapshot({ turnDeadline: new Date(Date.now() - 1000).toISOString() })
  await expect(panel(page)).toContainText('서버의 다음 차례를 기다리고 있습니다.')
  await expect(roll(page)).toBeDisabled(); await expect(panel(page)).not.toContainText('패배')
  expect(server.sent.filter(m => m.type === 'GAME_ACTION_SEND')).toHaveLength(2)
})
