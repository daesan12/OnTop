import { test, expect, type Page } from '@playwright/test'
import { fixture, screenshot } from './contractFixture'
const dice = (values: number[], held: number[] = []) => values.map((value, id) => ({ id, value, held: held.includes(id) }))
const panel = (p: Page) => p.getByRole('region', { name: '주사위 경기', exact: true })
async function start(page: Page) {
  const server = await fixture(page, { omok: true, dice: true, m09: true })
  await page.goto('/park')
  await expect(page).toHaveTitle(/온탑|OnTop/i)
  await expect(page.getByText('공원을 준비하고 있어요…')).toBeHidden({ timeout: 90_000 })
  await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).inspectTable())
  await page.getByRole('button', { name: '앉기', exact: true }).click()
  await page.getByRole('button', { name: '주사위 한 판 선택', exact: true }).click()
  await page.getByRole('button', { name: '준비', exact: true }).click()
  server.confirmStart()
  await expect(panel(page)).toContainText('내 차례')
  await expect(page.getByRole('region', { name: '오목 경기', exact: true })).toHaveCount(0)
  return server
}
const roll = (p: Page) => panel(p).getByRole('button', { name: /^R / })
const bank = (p: Page) => panel(p).getByRole('button', { name: /^Q Bank/ })
const die = (p: Page, id: number) => panel(p).getByRole('button', { name: new RegExp(`^주사위 ${id + 1}:`) })
const probe = (p: Page) => p.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).farkleProbe())

test('M11 uses exact roll/held selection/Hot Dice/Bank commands, public eyes, server win and existing settlement/next round', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
  const server = await start(page)
  server.holdState(true)
  server.diceReply({ kind: 'roll', selectedIds: [] }, { dice: dice([1, 2, 2, 2, 4, 5]), stage: 'SELECTING', rollId: 1, lastEvent: 'ROLL' })
  await roll(page).click()
  await expect(panel(page)).toContainText('처리 확인 수신')
  await expect(panel(page).getByRole('button', { name: /^주사위 \d:/ })).toHaveCount(0)
  await expect(roll(page)).toBeDisabled()
  server.flushGame()
  await expect(die(page, 1)).toBeEnabled()
  await die(page, 1).click(); await expect(bank(page)).toBeDisabled()
  await die(page, 2).click(); await die(page, 3).click(); await expect(bank(page)).toContainText('200점')
  await die(page, 1).click(); await die(page, 2).click(); await die(page, 3).click(); await die(page, 0).click()
  server.holdState(false)
  server.diceReply({ kind: 'roll', selectedIds: [0] }, { dice: dice([1, 1, 5, 3, 3, 3], [0]), turnScore: 100, rollId: 2 })
  await roll(page).click()
  await expect(die(page, 0)).toBeDisabled()
  await expect(panel(page)).toContainText('이번 턴 누적: 100점')
  await expect(die(page, 1)).toBeEnabled()
  for (const id of [1, 2, 3, 4, 5]) await die(page, id).click()
  server.diceReply({ kind: 'roll', selectedIds: [1, 2, 3, 4, 5] }, { dice: dice([1, 2, 3, 4, 5, 6]), turnScore: 550, rollId: 3, hotDice: true, lastEvent: 'HOT_DICE' })
  await roll(page).click()
  await expect(panel(page)).toContainText('HOT DICE')
  await expect(die(page, 0)).toBeEnabled()
  await panel(page).getByRole('button', { name: '주사위 판 보기', exact: true }).click()
  await expect.poll(async () => (await probe(page)).cameraReady).toBe(true)
  const render = await probe(page)
  expect(render.dice.map((d: { face: number }) => d.face)).toEqual([1, 2, 3, 4, 5, 6])
  // Original bone atlas: +X=3, -X=4, +Y=1, -Y=6, +Z=2, -Z=5.
  const normals = [[0, 1, 0], [0, 0, 1], [1, 0, 0], [-1, 0, 0], [0, 0, -1], [0, -1, 0]]
  for (const d of render.dice) {
    const [x, y, z, w] = d.quaternion, [nx, ny, nz] = normals[d.face - 1]!
    const topY = 2 * (x! * y! + z! * w!) * nx! + (1 - 2 * (x! * x! + z! * z!)) * ny! + 2 * (y! * z! - x! * w!) * nz!
    expect(topY).toBeCloseTo(1, 3)
  }
  await screenshot(page, 'm11-hot-dice')
  await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).watchDiceResources())
  for (const id of [0, 1, 2, 3, 4, 5]) await die(page, id).click()
  server.diceReply({ kind: 'bank', selectedIds: [0, 1, 2, 3, 4, 5] }, { scores: [2050, 0], status: 'FINISHED', stage: 'FINISHED',
    turnUserId: null, turnDeadline: null, winnerUserId: '101', endReason: 'TARGET_REACHED', endedAt: new Date().toISOString(), lastEvent: 'BANK' })
  await bank(page).click(); await expect(panel(page)).toContainText('승리'); await expect(panel(page)).toContainText('2,050점')
  await panel(page).getByRole('button', { name: '정산 결과 확인' }).click(); await expect(panel(page)).toContainText('정산 대기 중')
  server.settle(); await expect(panel(page)).toContainText('정산 완료 · 내 엽전 증감 1')
  await expect(page.getByLabel('보유 엽전', { exact: true })).toHaveText('100냥')
  server.nextRound(); await expect(panel(page)).toHaveCount(0)
  // The original textured dice use cached meshes; six per-die pip instance buffers are gone.
  await expect.poll(() => page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).diceResourceProbe())).toEqual({ disposed: 0, sharedDisposed: 0 })
  await expect(page.getByRole('button', { name: '준비', exact: true })).toBeEnabled()
  const actions = server.sent.filter(m => m.type === 'GAME_ACTION_SEND')
  expect(actions).toHaveLength(4)
  for (const action of actions) expect(Object.keys(action.payload).sort()).toEqual(['actionId', 'expectedVersion', 'gameId', 'input'])
  expect(server.maxActive).toBe(1); expect(errors).toEqual([])
})

