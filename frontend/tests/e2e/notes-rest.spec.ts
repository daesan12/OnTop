test('M08 keeps login on business 403 and honors write cooldown and terminal 410 on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const server = await fixture(page, { manualMovement: true, position: near }); const rest = await notesFixture(page)
  rest.readMode('outOfRange'); await loaded(page)
  await expect(dialog(page).getByRole('alert')).toContainText('전망대 정상 메모함 가까이')
  expect(page.url()).toContain('/park'); expect(server.connections).toBe(1)
  rest.readMode('normal'); await expect(wall(page)).toContainText('아직 메모가 없어요', { timeout: 6000 })
  rest.writeMode('writeCooldown'); await area(page).fill(body)
  await dialog(page).getByRole('button', { name: '익명으로 붙이기', exact: true }).click()
  await expect(dialog(page).getByRole('button', { name: /초 후 붙이기/ })).toBeDisabled()
  expect((await probe(page)).nextAllowedAt).toBe(Date.parse(rest.deadline))
  await expect(area(page)).toHaveValue(body)
  rest.writeMode('expired')
  const retry = dialog(page).getByRole('button', { name: '같은 메모 다시 붙이기', exact: true })
  await expect(retry).toBeEnabled({ timeout: 10000 }); await retry.click()
  await expect(dialog(page)).toContainText('재확인 기간이 만료'); await expect(retry).toBeDisabled()
  const key = rest.requests[0]!.operationId
  expect(rest.requests[1]!.operationId).toBe(key); await expect(area(page)).toHaveValue(body)
  await screenshot(page, 'm08-rest-mobile-expired')
  await page.keyboard.press('Escape'); await open(page); await expect(retry).toBeDisabled()
  expect(rest.requests).toHaveLength(2)
  await area(page).fill('새로 작성한 마음 한 장'); await expect(dialog(page).getByRole('button', { name: '익명으로 붙이기', exact: true })).toBeEnabled()
  const box = await dialog(page).boundingBox(); expect(box!.x + box!.width).toBeLessThanOrEqual(390); expect(box!.y + box!.height).toBeLessThanOrEqual(844)
})
test('M08 avoids overlapping slow reads, respects read deadlines and keeps the existing list on failure', async ({ page }) => {
  await fixture(page, { manualMovement: true, position: near }); const rest = await notesFixture(page)
  rest.add('이전에 확인한 메모'); await loaded(page); rest.readMode('holdRead')
  await expect.poll(() => rest.reads).toBe(2)
  await page.waitForTimeout(4200); expect(rest.reads).toBe(2)
  rest.readMode('readCooldown'); await rest.release()
  await expect.poll(() => rest.reads).toBe(3)
  await expect(dialog(page).getByRole('alert')).toContainText('목록 조회 간격')
  await expect(wall(page)).toContainText('이전에 확인한 메모')
  await page.waitForTimeout(2500); expect(rest.reads).toBe(3)
  rest.readMode('normal'); await expect.poll(() => rest.reads, { timeout: 6000 }).toBe(4)
  expect(rest.readTimes[3]! - rest.readTimes[2]!).toBeGreaterThanOrEqual(5900)
  await expect(dialog(page).getByRole('alert')).toHaveCount(0)
})
test('M08 cancels polls and late replies across close, ground movement, reconnect and auth end', async ({ page }) => {
  const server = await fixture(page, { manualMovement: true, position: near }); const rest = await notesFixture(page)
  await loaded(page); rest.writeMode('hold'); await area(page).fill(body)
  await dialog(page).getByRole('button', { name: '익명으로 붙이기', exact: true }).click()
  await expect.poll(() => rest.acceptedCount).toBe(1); const original = { ...rest.requests[0]! }
  server.close(1013); await expect(dialog(page)).toBeHidden(); await expect.poll(() => server.connections).toBe(2)
  const reads = rest.reads; await page.waitForTimeout(2500); expect(rest.reads).toBe(reads)
  await open(page); await expect(area(page)).toHaveValue(body)
  rest.writeMode('normal'); await dialog(page).getByRole('button', { name: '같은 메모 다시 붙이기', exact: true }).click()
  await expect(area(page)).toHaveValue(''); expect(rest.requests).toEqual([original, original]); expect(rest.acceptedCount).toBe(1)
  await area(page).fill('새로 작성 중인 메모'); await rest.release(); await expect(area(page)).toHaveValue('새로 작성 중인 메모')
  server.pose({ ...near, y: .8 }); await expect(dialog(page)).toBeHidden()
  const count = rest.reads; await page.waitForTimeout(2500); expect(rest.reads).toBe(count)
  expect((await probe(page)).draft).toBe('새로 작성 중인 메모')
  server.pose(near); await open(page); server.endSession(); await expect(page.locator('.login-page')).toBeVisible()
  const finalCount = rest.reads; await page.waitForTimeout(2500); expect(rest.reads).toBe(finalCount); expect((await probe(page)).draft).toBe('')
})
