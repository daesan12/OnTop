import { expect, test, type Page } from '@playwright/test'
import { fixture, screenshot } from './contractFixture'
import { notesFixture } from './notesFixture'
import { NOTES_BOX } from '../../src/config/notes'

const near = { x: NOTES_BOX.x - 1.5, y: NOTES_BOX.y + .8, z: NOTES_BOX.z, yaw: 0 }
const body = '오늘도 좋은 하루 보내세요. 전망대에서 마음 한 장 남겨요.'
const dialog = (p: Page) => p.getByRole('dialog', { name: '전망대 익명 메모', exact: true })
const area = (p: Page) => dialog(p).getByLabel('새 메모', { exact: true })
const wall = (p: Page) => dialog(p).getByRole('region', { name: '익명 메모 목록' })
const probe = (p: Page): Promise<ReturnType<typeof import('./sceneProbe').notesProbe>> =>
  p.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).notesProbe())
async function open(p: Page) {
  await p.getByLabel('가까운 상호작용').getByRole('button', { name: /익명 메모 소리함 열기/ }).click()
  await expect(dialog(p)).toBeVisible(); await expect(area(p)).toBeFocused()
  await expect(wall(p)).toHaveAttribute('aria-busy', 'false')
}
async function loaded(p: Page) {
  await p.goto('/park'); await expect(p).toHaveTitle('OnTop')
  await expect(p.getByLabel('공원 기본 화면')).toBeVisible()
  await expect(p.getByText('공원을 준비하고 있어요…')).toBeHidden({ timeout: 90_000 })
  await p.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).orbit(0, .35, 6.8))
  await open(p)
}
test('M08 reads and posts authenticated anonymous REST, then polls another note and restores input on close', async ({ page }) => {
  const errors: string[] = [], consoleErrors: string[] = []
  page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error') consoleErrors.push(m.text()) })
  const server = await fixture(page, { manualMovement: true, position: near })
  const rest = await notesFixture(page); await loaded(page)
  await expect(wall(page)).toContainText('아직 메모가 없어요'); await expect(dialog(page)).toContainText('2초 간격')
  rest.writeMode('hold'); const raw = '  ' + body + '\u200b\n'
  await area(page).fill(raw); await dialog(page).getByRole('button', { name: '익명으로 붙이기', exact: true }).click()
  await expect.poll(() => rest.acceptedCount).toBe(1)
  await expect(area(page)).toHaveValue(raw); await expect(area(page)).toHaveJSProperty('readOnly', true)
  await rest.release(); await expect(dialog(page)).toContainText('익명 메모를 붙였어요. 고맙습니다!')
  await expect(area(page)).toHaveValue(''); await expect(wall(page).getByText(body, { exact: true })).toHaveCount(1)
  rest.add('다른 이웃이 남긴 새 메모')
  await expect(wall(page).getByText('다른 이웃이 남긴 새 메모', { exact: true })).toBeVisible({ timeout: 6000 })
  expect(rest.requests[0]).toMatchObject({ channelId: 'fixture-channel', text: body })
  expect((await probe(page)).publicData).not.toContain(body); expect(JSON.stringify(server.sent)).not.toContain(body)
  expect(Object.keys((await probe(page)).notes[0]!).sort()).toEqual(['createdAt', 'id', 'text'])
  await screenshot(page, 'm08-rest-posted-and-polled')
  await page.keyboard.press('Escape'); await expect(dialog(page)).toBeHidden()
  const reads = rest.reads; await page.waitForTimeout(2500); expect(rest.reads).toBe(reads)
  await page.keyboard.down('KeyW')
  await expect.poll(() => server.sent.some(m => m.type === 'WORLD_MOVE' && (m.payload.dx || m.payload.dz))).toBe(true)
  await page.keyboard.up('KeyW')
  expect(await page.locator('vite-error-overlay').count()).toBe(0); expect(errors).toEqual([]); expect(consoleErrors).toEqual([])
})
