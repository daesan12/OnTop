import { expect, test, type Page } from '@playwright/test'
import { fixture, screenshot } from './contractFixture'
import { MAILBOX } from '../../src/config'

const near = { x: MAILBOX.x - 1.5, y: 0.8, z: MAILBOX.z, yaw: 0 }
const body = '나만 작성한 소리함 의견입니다. 산책로 안내를 늘려주세요.'
const dialog = (page: Page) => page.getByRole('dialog', { name: '온탑 소리함' })
const area = (page: Page) => dialog(page).getByLabel('의견 내용')
const hint = (page: Page) => page.getByLabel('가까운 상호작용').getByRole('button', { name: /소리함에 의견 쓰기/ })
async function probe(page: Page): Promise<ReturnType<typeof import('./sceneProbe').feedbackProbe>> {
  return page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).feedbackProbe())
}
async function fault(page: Page, mode: 'normal' | 'reject' | 'hold' | 'acceptThenLose') {
  await page.evaluate(async mode => (await import('/tests/e2e/sceneProbe.ts' as string)).fixtureFeedback(mode), mode)
}
async function loaded(page: Page, expectNearbyHint = true) {
  await page.goto('/park')
  await expect(page).toHaveTitle('OnTop')
  await expect(page.getByLabel('공원 기본 화면')).toBeVisible()
  await expect(page.getByText('공원을 준비하고 있어요…')).toBeHidden({ timeout: 90_000 })
  await page.locator('canvas').focus()
  await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).orbit(0, 0.35, 6.8))
  if (expectNearbyHint) await expect(hint(page)).toBeEnabled()
}

test('M07 shares the ground E target, isolates typing/roaming and retains a failed private draft until retry approval', async ({ page, context }) => {
  const errors: string[] = [], consoleErrors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') consoleErrors.push(message.text()) })
  const server = await fixture(page, { manualMovement: true, position: near })
  await loaded(page)
  const observer = await context.newPage()
  const other = await fixture(observer, { manualMovement: true, position: near, ownUserId: '102' })
  await loaded(observer, false)
  await page.bringToFront()
  const controls = (await probe(page)).controls
  await page.locator('canvas').focus()
  await page.keyboard.press('KeyE')
  await expect(dialog(page)).toBeVisible()
  await expect(area(page)).toBeFocused()
  await expect(dialog(page)).not.toContainText('개발 목업')
  await expect(dialog(page).getByRole('button', { name: '의견 보내기', exact: true })).toBeDisabled()
  await area(page).fill('네 글자')
  await expect(dialog(page).getByRole('button', { name: '의견 보내기', exact: true })).toBeDisabled()
  await page.keyboard.press('KeyW'); await page.keyboard.press('KeyG'); await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog', { name: '감정표현 선택' })).toBeHidden()
  await expect(page.getByLabel('주변 채팅 메시지')).toBeHidden()
  const typingBox = await area(page).boundingBox()
  await page.mouse.move(typingBox!.x + 20, typingBox!.y + 20); await page.mouse.down()
  await page.mouse.move(typingBox!.x + 100, typingBox!.y + 40); await page.mouse.up()
  await page.mouse.wheel(0, -300)
  expect((await probe(page)).controls).toEqual(controls)
  expect(server.sent.some(m => m.type === 'WORLD_MOVE' && (m.payload.dx || m.payload.dz || m.payload.jump))).toBe(false)
  await area(page).fill(body)
  await fault(page, 'reject')
  await dialog(page).getByRole('button', { name: '의견 보내기', exact: true }).click()
  await expect(dialog(page).getByRole('alert')).toContainText('저장 실패')
  await expect(area(page)).toHaveValue(body)
  const key = (await probe(page)).operationId
  await screenshot(page, 'm07-failure-retains-draft')
  await fault(page, 'normal')
  await dialog(page).getByRole('button', { name: '같은 의견 다시 보내기', exact: true }).click()
  await expect(dialog(page).getByRole('status')).toContainText('의견을 전달했어요. 고맙습니다!')
  await expect(area(page)).toHaveValue('')
  const state = await probe(page)
  expect(state.calls.map(call => call.operationId)).toEqual([key, key])
  expect(state.publicData).not.toContain(body)
  expect(JSON.stringify(server.sent)).not.toContain(body)
  expect(JSON.stringify(other.sent)).not.toContain(body)
  await expect(observer.getByText(body, { exact: true })).toHaveCount(0)
  await expect(dialog(observer)).toBeHidden()
  await screenshot(page, 'm07-confirmed')
  await page.keyboard.press('Escape')
  await expect(dialog(page)).toBeHidden()
  await page.keyboard.down('KeyW')
  await expect.poll(() => server.sent.some(m => m.type === 'WORLD_MOVE' && (m.payload.dx || m.payload.dz))).toBe(true)
  await page.keyboard.up('KeyW')
  await expect(page.locator('vite-error-overlay')).toHaveCount(0)
  expect(errors).toEqual([])
  expect(consoleErrors).toEqual([])
  await observer.close()
})

test('M07 times out an accepted but lost response, retries the same request without another receipt and clears only after acknowledgement', async ({ page }) => {
  const server = await fixture(page, { manualMovement: true, position: near })
  await loaded(page)
  await hint(page).click()
  await area(page).fill(body)
  await fault(page, 'acceptThenLose')
  await dialog(page).getByRole('button', { name: '의견 보내기', exact: true }).click()
  await expect.poll(async () => (await probe(page)).accepted.length).toBe(1)
  await expect(dialog(page).getByRole('alert')).toContainText('응답 시간이 초과', { timeout: 15_000 })
  await expect(area(page)).toHaveValue(body)
  const before = await probe(page)
  expect(before.pending).toBe(false)
  await dialog(page).getByRole('button', { name: '같은 의견 다시 보내기', exact: true }).click()
  await expect(dialog(page).getByRole('status')).toContainText('의견을 전달했어요. 고맙습니다!')
  const after = await probe(page)
  expect(after.accepted).toEqual([before.accepted[0], before.accepted[0]])
  expect(after.calls.map(call => call.operationId)).toEqual([before.operationId, before.operationId])
  await expect(area(page)).toHaveValue('')
  expect(server.sent.some(m => /FEEDBACK|feedback-submit/.test(m.type))).toBe(false)
})

test('M07 cancels a closed or disconnected visit, restores the same user draft and purges it when authentication ends', async ({ page }) => {
  const server = await fixture(page, { manualMovement: true, position: near })
  await loaded(page)
  await hint(page).click()
  await area(page).fill(body)
  await fault(page, 'hold')
  await dialog(page).getByRole('button', { name: '의견 보내기', exact: true }).click()
  await expect.poll(async () => (await probe(page)).pending).toBe(true)
  await page.keyboard.press('Escape')
  await expect(dialog(page)).toBeHidden()
  const previous = await probe(page)
  expect(previous.pending).toBe(false)
  await hint(page).click()
  await expect(area(page)).toHaveValue(body)
  await dialog(page).getByRole('button', { name: '같은 의견 다시 보내기', exact: true }).click()
  await expect.poll(async () => (await probe(page)).pending).toBe(true)
  server.close(1012)
  await expect(dialog(page)).toBeHidden()
  await expect.poll(() => server.connections, { timeout: 15_000 }).toBe(2)
  await expect(hint(page)).toBeEnabled()
  await hint(page).click()
  await expect(area(page)).toHaveValue(body)
  expect((await probe(page)).operationId).toBe(previous.operationId)
  expect((await probe(page)).feedbackOpen).toBe(true)
  server.endSession()
  await expect(page.locator('.login-page')).toBeVisible()
  expect((await probe(page)).draft).toBe('')
  expect((await probe(page)).ownerId).toBe('')
})

test('M07 keeps a narrow-screen dialog usable and closes a remote/high approach without losing text', async ({ page }) => {
  const server = await fixture(page, { manualMovement: true, position: near })
  await loaded(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await hint(page).click()
  await area(page).fill(body)
  const box = await dialog(page).boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(390)
  expect(box!.y).toBeGreaterThanOrEqual(0)
  expect(box!.y + box!.height).toBeLessThanOrEqual(844)
  await page.keyboard.press('Tab')
  expect(await dialog(page).evaluate(node => node.contains(document.activeElement))).toBe(true)
  await screenshot(page, 'm07-mobile')
  server.pose({ ...near, y: 12 })
  await expect(dialog(page)).toBeHidden()
  expect((await probe(page)).draft).toBe(body)
  expect(await page.evaluate(async () => (await import('/src/features/feedback/controller.ts' as string)).openFeedback())).toBe(false)
})
