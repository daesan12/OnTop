import { test, expect } from '@playwright/test'
import { fixture, screenshot, tableId } from './contractFixture'

test('M09 preview mocks only the public match reference; real WS public snapshots drive spectator camera and never grant input', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  const server = await fixture(page, { omok: true, m09: true })
  await page.goto('/park')
  await expect(page.getByText('공원을 준비하고 있어요…')).toBeHidden({ timeout: 90_000 })
  await page.locator('canvas').click({ position: { x: 80, y: 300 } }); await page.keyboard.press('KeyE')
  const lobby = page.getByRole('dialog', { name: '테이블 정보', exact: true })
  await page.evaluate(async tableId => (await import('/tests/e2e/sceneProbe.ts' as string)).previewPublicMatch({ channelId: 'fixture-channel', tableId, gameId: 'fixture-confirmed-omok' }), tableId)
  await lobby.getByRole('button', { name: '미리보기 경기 참조 확인' }).click()
  server.rejectGameWatch(true)
  await lobby.getByRole('button', { name: '경기 관전', exact: true }).click()
  await expect(lobby).toBeVisible()
  await expect(page.getByRole('region', { name: '오목 경기', exact: true }).getByRole('group', { name: '오목판', exact: true })).toHaveCount(0)
  server.rejectGameWatch(false)
  await lobby.getByRole('button', { name: '경기 관전', exact: true }).click()
  const panel = page.getByRole('region', { name: '오목 경기', exact: true })
  await expect(panel).toContainText('오목 관전')
  await expect(panel).toContainText('흑 차례')
  await expect(panel).not.toContainText('내 차례')
  await expect(page.getByRole('button', { name: 'E 테이블 정보 보기', exact: true })).toHaveCount(0)
  await expect(panel.getByRole('button', { name: '8행 8열 빈칸', exact: true })).toBeDisabled()
  await expect.poll(() => page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).tablePresentationProbe().omokCamera.ready)).toBe(true)
  const before = await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).tablePresentationProbe())
  expect(before.ownTable).toBe(''); expect(before.seatIndex).toBe(-1)
  await screenshot(page, 'm09-spectator-board')
  await panel.getByRole('button', { name: '테이블 둘러보기' }).click()
  await expect.poll(() => page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).tablePresentationProbe().omokCamera.ready)).toBe(false)
  await screenshot(page, 'm09-spectator-table')
  expect(server.sent.find(m => m.type === 'GAME_WATCH')?.payload).toEqual({ gameId: 'fixture-confirmed-omok' })
  expect(server.sent.some(m => m.type === 'GAME_ACTION_SEND')).toBe(false)
  await panel.getByRole('button', { name: '관전 종료', exact: true }).click()
  await expect(panel).toHaveCount(0)
  await expect(lobby).toBeVisible()
  await lobby.getByRole('button', { name: '앉기', exact: true }).click()
  await lobby.getByRole('button', { name: '테이블 정보 닫기' }).click()
  const canvas = page.locator('canvas')
  await canvas.click({ position: { x: 80, y: 300 } })
  await page.mouse.move(600, 400); await page.mouse.down({ button: 'right' }); await page.mouse.move(740, 400, { steps: 8 }); await page.mouse.up({ button: 'right' })
  await expect.poll(() => page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).tablePresentationProbe().yaw)).not.toBe(0)
  await page.getByRole('button', { name: '테이블 로비 열기' }).click()
  await lobby.getByRole('button', { name: '정면 보기', exact: true }).click()
  await expect.poll(() => page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).tablePresentationProbe().yaw)).toBe(0)
  await lobby.getByRole('button', { name: '일어나기', exact: true }).click()
  expect(errors).toEqual([])
})
