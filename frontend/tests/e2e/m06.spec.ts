import { expect, test, type Page } from '@playwright/test'
import { fixture, screenshot } from './contractFixture'
import { TELESCOPE, TELESCOPES, telescopeFov } from '../../src/config'
import { telescopeAnchors } from '../../src/features/telescopes/anchors'

const t = TELESCOPES[0]!, other = TELESCOPES[1]!
async function probe(page: Page, id = t.id): Promise<ReturnType<typeof import('./sceneProbe').telescopeProbe>> {
  return page.evaluate(async id => (await import('/tests/e2e/sceneProbe.ts' as string)).telescopeProbe(id), id)
}
async function loaded(page: Page) {
  await page.goto('/park')
  await expect(page).toHaveTitle('OnTop')
  await expect(page.getByLabel('공원 기본 화면')).toBeVisible()
  await expect(page.getByText('공원을 준비하고 있어요…')).toBeHidden({ timeout: 90_000 })
  await page.locator('canvas').focus()
  await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).orbit(0, 0.35, 6.8))
}
const panel = (page: Page) => page.getByRole('complementary', { name: '전망 망원경', exact: true })
const hint = (page: Page) => page.getByLabel('가까운 상호작용')
async function centeredReticle(page: Page) {
  const canvas = await page.locator('canvas').boundingBox(), reticle = await page.locator('.telescope-viewfinder span').boundingBox()
  expect(Math.abs(reticle!.x + reticle!.width / 2 - canvas!.x - canvas!.width / 2)).toBeLessThan(1)
  expect(Math.abs(reticle!.y + reticle!.height / 2 - canvas!.y - canvas!.height / 2)).toBeLessThan(1)
}

test('M06 rejects ground entry, uses the summit E target, aims/zooms locally and restores camera/input after E/Esc', async ({ page }) => {
  const errors: string[] = [], consoleErrors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') consoleErrors.push(message.text()) })
  const approach = telescopeAnchors(t.id).use
  const server = await fixture(page, { manualMovement: true, position: { ...approach, y: 0.8 } })
  await loaded(page)
  expect(await page.evaluate(async id => (await import('/src/features/telescopes/controller.ts' as string)).enterTelescope(id), t.id)).toBe(false)
  await expect(panel(page)).toBeHidden()
  server.pose(approach)
  await expect(hint(page).getByRole('button', { name: new RegExp(t.name) })).toBeEnabled()
  const baseline = await probe(page)
  await page.keyboard.press('KeyE')
  await expect(panel(page)).toBeVisible()
  await centeredReticle(page)
  const initial = await probe(page)
  expect(initial.id).toBe(t.id)
  expect(initial.ownVisible).toBe(false)
  expect(initial.instrumentVisible).toBe(false)
  expect(initial.authoritative).toEqual(approach)
  expect(initial.camera).toEqual([t.position[0], t.position[1] + TELESCOPE.eyeHeight, t.position[2]])
  expect(initial.fov).toBeCloseTo(telescopeFov(baseline.fov, 3))
  const count = server.sent.filter(m => m.type === 'WORLD_MOVE' && (m.payload.dx || m.payload.dz || m.payload.jump)).length
  await page.keyboard.press('KeyW')
  await page.keyboard.press('Space')
  expect((await probe(page)).id).toBe(t.id)
  expect(server.sent.filter(m => m.type === 'WORLD_MOVE' && (m.payload.dx || m.payload.dz || m.payload.jump))).toHaveLength(count)
  await page.mouse.move(800, 350)
  await page.mouse.down()
  await page.mouse.move(960, 390, { steps: 12 })
  await page.mouse.up()
  await expect.poll(async () => (await probe(page)).view.yaw).not.toBe(initial.view.yaw)
  await expect.poll(async () => (await probe(page)).placements['101']?.yaw).toBe((await probe(page)).view.yaw)
  await page.getByRole('button', { name: '망원경 확대', exact: true }).click()
  await expect(page.getByLabel('확대 배율')).toHaveText('3.5×')
  await page.mouse.move(800, 350)
  await page.mouse.wheel(0, -2000)
  await expect(page.getByLabel('확대 배율')).toHaveText('8.0×')
  const zoomed = await probe(page)
  expect(zoomed.fov).toBeCloseTo(telescopeFov(baseline.fov, 8))
  expect(zoomed.controls).toEqual(baseline.controls)
  await page.keyboard.press('F1')
  const guide = page.getByRole('dialog', { name: '망원경 조작 설명' })
  await expect(guide).toBeVisible()
  const locked = await probe(page)
  await page.keyboard.press('KeyE')
  await page.mouse.move(800, 350); await page.mouse.down(); await page.mouse.move(950, 450); await page.mouse.up()
  await page.mouse.wheel(0, 500)
  expect((await probe(page)).view).toEqual(locked.view)
  await page.keyboard.press('Escape')
  await expect(guide).toBeHidden()
  await expect(panel(page)).toBeVisible()
  await screenshot(page, 'm06-viewfinder')
  await page.keyboard.press('Escape')
  await expect(panel(page)).toBeHidden()
  await expect.poll(async () => (await probe(page)).fov).toBe(baseline.fov)
  const restored = await probe(page)
  expect(restored.controls).toEqual(baseline.controls)
  expect(restored.displayed).toEqual(approach)
  expect(restored.ownVisible).toBe(true)
  await page.keyboard.down('KeyW')
  await expect.poll(() => server.sent.filter(m => m.type === 'WORLD_MOVE' && (m.payload.dx || m.payload.dz)).length).toBeGreaterThan(count)
  await page.keyboard.up('KeyW')
  await page.keyboard.press('KeyE')
  await expect(panel(page)).toBeVisible()
  await page.keyboard.press('KeyE')
  await expect(panel(page)).toBeHidden()
  expect(server.sent.some(m => /TELESCOPE/.test(m.type))).toBe(false)
  expect(await page.locator('vite-error-overlay').count()).toBe(0)
  expect(errors).toEqual([])
  expect(consoleErrors).toEqual([])
})

test('M06 retains remote approved direction, independent instruments and cleans camera/leases on reconnect', async ({ page }) => {
  const approach = telescopeAnchors(t.id).use
  const server = await fixture(page, { manualMovement: true, position: approach })
  await loaded(page)
  const baseline = await probe(page)
  await page.evaluate(async id => (await import('/tests/e2e/sceneProbe.ts' as string)).fixtureTelescope('102', id, 0.55, -0.3), t.id)
  await expect(hint(page)).toContainText('산책자 102 님이 사용 중')
  await expect(hint(page).getByRole('button')).toBeDisabled()
  await page.keyboard.press('KeyE')
  await expect(panel(page)).toBeHidden()
  expect((await probe(page)).remote).toEqual({ id: t.id, yaw: 0.55, pitch: -0.3 })
  await expect.poll(async () => Math.abs(((await probe(page)).swivel ?? Infinity) - 0.55)).toBeLessThan(0.01)
  await expect.poll(async () => Math.abs(((await probe(page)).head ?? Infinity) - 0.3)).toBeLessThan(0.01)
  expect((await probe(page)).remoteVisible).toBe(true)
  await screenshot(page, 'm06-remote-owner')
  server.pose(telescopeAnchors(other.id).use)
  await expect(hint(page).getByRole('button', { name: new RegExp(other.name) })).toBeEnabled()
  await page.locator('canvas').focus()
  await page.keyboard.press('KeyE')
  await expect(panel(page)).toHaveAttribute('data-telescope-id', other.id)
  expect(Object.keys((await probe(page)).placements)).toHaveLength(2)
  server.players(1)
  await expect.poll(async () => Object.keys((await probe(page)).placements)).toEqual(['101'])
  await page.keyboard.press('F1')
  await expect(page.getByRole('dialog', { name: '망원경 조작 설명' })).toBeVisible()
  server.close(1012)
  await expect.poll(() => server.connections, { timeout: 15_000 }).toBe(2)
  await expect(panel(page)).toBeHidden()
  await expect(page.getByRole('dialog', { name: '망원경 조작 설명' })).toBeHidden()
  await expect.poll(async () => Object.keys((await probe(page)).placements).length).toBe(0)
  expect((await probe(page)).view.id).toBe('')
  await expect.poll(async () => (await probe(page)).ownVisible).toBe(true)
  await expect.poll(async () => (await probe(page)).fov).toBe(baseline.fov)
  expect((await probe(page)).controls).toEqual(baseline.controls)
  expect(server.maxActive).toBe(1)
})

test('M06 keeps narrow-screen zoom, guide and exit controls within the viewport', async ({ page }) => {
  await fixture(page, { manualMovement: true, position: telescopeAnchors(t.id).use })
  await loaded(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await hint(page).getByRole('button', { name: new RegExp(t.name) }).click()
  await expect(panel(page)).toBeVisible()
  await centeredReticle(page)
  const box = await panel(page).boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(390)
  await page.getByRole('button', { name: '망원경 축소', exact: true }).click()
  await expect(page.getByLabel('확대 배율')).toHaveText('2.5×')
  await page.getByRole('button', { name: '망원경 설명서 열기' }).click()
  await expect(page.getByRole('dialog', { name: '망원경 조작 설명' })).toBeVisible()
  await page.getByRole('button', { name: '설명서 닫기 · F1 / Esc' }).click()
  await screenshot(page, 'm06-mobile')
  await page.getByRole('button', { name: '망원경에서 나가기', exact: true }).click()
  await expect(panel(page)).toBeHidden()
})
