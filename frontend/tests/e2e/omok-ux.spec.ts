  const server = await fixture(page, { omok: true, publicSpectator: true, spectatorEvents: true })
  await load(page)
  await page.evaluate(async () => {
    const { TABLES } = await import('/src/config/index.ts' as string)
    ;(await import('/src/features/tableLobby/tableInteraction.ts' as string)).interactWithTable(TABLES[0].id)
  })
  const panel = page.getByRole('dialog', { name: '테이블 정보', exact: true })
  await expect(panel).toBeVisible()
  await expect(panel.getByRole('button', { name: '앉기', exact: true })).toBeDisabled()
