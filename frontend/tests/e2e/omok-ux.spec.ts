async function boardFitsHud(page: Page) {
  const state = await camera(page), viewport = page.viewportSize()!
  const points = state.corners as number[][]
  const board = { left: Math.min(...points.map(p => p[0]!)), right: Math.max(...points.map(p => p[0]!)),
    top: Math.min(...points.map(p => p[1]!)), bottom: Math.max(...points.map(p => p[1]!)) }
  expect(state).toMatchObject({ layers: 2, rayLayers: 2, backdrop: true, ready: true, viewport: [viewport.width, viewport.height] })
  expect(board.left).toBeGreaterThan(10); expect(board.right).toBeLessThan(viewport.width - 10)
  expect(board.top).toBeGreaterThan(10); expect(board.bottom).toBeLessThan(viewport.height - 10)
  for (const hud of await page.locator('.omok-match-header,.game-hud-clock,.omok-play-tools,.omok-play-notes,.omok-spectator-toolbar,.park-chat').all()) {
    if (!await hud.isVisible()) continue
    const box = (await hud.boundingBox())!
    const separated = board.right <= box.x || board.left >= box.x + box.width
      || board.bottom <= box.y || board.top >= box.y + box.height
    expect(separated, `board overlaps ${await hud.getAttribute('class')} at ${viewport.width}x${viewport.height}`).toBe(true)
  }
}
