test('approved observer sends game chat and board ping, without ever placing a stone',async({page})=>{
  const {facilityCatalog}=await import('../fixtures/facilityCatalog')
  const {benchTable}=await import('../../src/features/interactions/benchSpectator')
  const bench=facilityCatalog.facilities.find(d=>d.kind==='BENCH' && benchTable(d.facilityId)?.pavilionId==='P1')!
  const anchor=benchTable(bench.facilityId)!
  const server=await fixture(page,{omok:true,publicSpectator:true,spectatorEvents:true,manualMovement:true,position:bench.center,anchorId:anchor.id})
  await load(page)
  expect(await page.evaluate(async id=>(await import('/src/features/interactions/benchController.ts' as string)).sitBench(id,0),bench.facilityId)).toBe(true)
  await page.getByRole('button',{name:'가까이 관전',exact:true}).click()
  const input=page.getByLabel('관전 채팅 · 판을 눌러 위치 추천')
  await expect(input).toBeEnabled(); await input.fill('여기 어때요?')
  await page.getByRole('button',{name:'보내기',exact:true}).click()
  await expect(page.locator('.omok-floating-chat')).toContainText('여기 어때요?')
  expect(server.sent.filter(m=>m.type==='GAME_SPECTATOR_CHAT_SEND')).toHaveLength(1)
  await page.getByRole('button',{name:'공개 판 보기',exact:true}).click()
  await expect.poll(()=>page.evaluate(async()=>(await import('/src/game/cameraState.ts' as string)).omokCamera.ready)).toBe(true)
  const point=await page.evaluate(async()=> (await import('/tests/e2e/sceneProbe.ts' as string)).pointForOmok(0,14))
  await page.mouse.click(point.x,point.y)
  await expect.poll(()=>server.sent.filter(m=>m.type==='OMOK_SPECTATOR_PING_SEND').length).toBe(1)
  expect(server.sent.find(m=>m.type==='OMOK_SPECTATOR_PING_SEND')?.payload).toMatchObject({x:0,y:14})
  await expect(page.locator('.omok-ping-label')).toHaveCount(1)
  await screenshot(page,'omok-ux-observer')
  expect(server.sent.filter(m=>m.type==='GAME_ACTION_SEND')).toHaveLength(0)
  await page.getByRole('button',{name:'관전 종료',exact:true}).click()
  await expect(page.locator('.omok-ping-label')).toHaveCount(0)
})
