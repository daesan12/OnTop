const camera = (page: Page) => page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).omokCameraProbe())
const currentGame = (page: Page) => page.evaluate(async () => (await import('/src/game/store.ts' as string)).useGame.getState().game)
async function load(page: Page) {
  await page.goto('/park'); await expect(page).toHaveTitle(/OnTop/i)
  await expect(page.getByText('공원을 준비하고 있어요…')).toBeHidden({timeout:90_000})
  await expect(page.locator('canvas')).toBeVisible({timeout:90_000})
  await expect.poll(() => page.evaluate(async () => {
    const { useSession } = await import('/src/network/worldClient.ts' as string)
    const { useFacilityState } = await import('/src/features/facilities/state.ts' as string)
    const s = useSession.getState()
    const f = useFacilityState.getState()
    return s.status === 'connected' && s.mapCompatible && !s.pending && s.tables.length > 0
      && f.ready && !f.pending && !f.awaitingWorld && !f.uncertain
  })).toBe(true)
}
