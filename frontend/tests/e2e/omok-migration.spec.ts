import { test, expect, type Page } from '@playwright/test'
import { fixture, screenshot } from './contractFixture'

async function start(page: Page, ownUserId: '101' | '102' = '101') {
  const server = await fixture(page, { omok: true, ownUserId })
  await page.goto('/park')
  await expect(page).toHaveTitle(/온탑|OnTop/i)
  await expect(page.getByText('공원을 준비하고 있어요…')).toBeHidden({ timeout: 90_000 })
  await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).inspectTable())
  await page.getByRole('button', { name: '앉기', exact: true }).click()
  if (ownUserId === '101') {
    await page.getByLabel('1인 참가비').fill('1'); await page.getByRole('button', { name: '오목 선택', exact: true }).click()
    await page.getByRole('button', { name: '준비', exact: true }).click()
  }
  server.confirmStart()
  if (ownUserId === '102') server.turnTo('102')
  const panel = page.locator('[aria-label="오목 경기"], .gathering-hud[data-phase="finished"], [aria-label="경기 결과 상세"]')
  await expect(panel).toContainText('내 차례')
  await panel.getByText('키보드로 오목판 조작', { exact: true }).click()
  return { server, panel }
}
const probe = (page: Page) => page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).omokPresentationProbe())
const point = (page: Page, x: number, y: number) => page.evaluate(async ({ x, y }) =>
  (await import('/tests/e2e/sceneProbe.ts' as string)).pointForOmok(x, y), { x, y })

test('M10 3D hover, same-intersection left click and last move share server authority', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  const { server, panel } = await start(page)
  await expect.poll(() => page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).omokCameraReady())).toBe(true)
  const p = await point(page, 7, 7)
  await page.mouse.move(p.x, p.y)
  await expect.poll(async () => (await probe(page)).hover).toBe(true)
  expect(server.sent.some(m => m.type === 'GAME_ACTION_SEND')).toBe(false)
  await screenshot(page, 'm10-hover')
  await page.mouse.click(p.x, p.y, { button: 'right' })
  expect(server.sent.some(m => m.type === 'GAME_ACTION_SEND')).toBe(false)
  // Even less than five screen pixels must not turn a boundary-crossing drag into another cell.
  const adjacent = await point(page, 8, 7), middle = (p.x + adjacent.x) / 2
  await page.mouse.move(middle - 1, p.y); await page.mouse.down(); await page.mouse.move(middle + 1, p.y); await page.mouse.up()
  expect(server.sent.some(m => m.type === 'GAME_ACTION_SEND')).toBe(false)
  await page.mouse.click(p.x, p.y)
  await expect(panel).toContainText('마지막 수: 흑 · 8행 8열')
  await expect(panel.getByRole('button', { name: '8행 8열 흑돌', exact: true })).toHaveAttribute('aria-current', 'true')
  await expect.poll(async () => (await probe(page)).lastMove).not.toBeNull()
  await expect.poll(async () => (await probe(page)).hover).toBe(false)
  await expect(panel).toContainText('상대 차례')
  await expect(panel.getByRole('button', { name: '기권', exact: true })).toBeDisabled()
  await expect(panel).toContainText('수동 기권은 서버 API 연결 후')
  await screenshot(page, 'm10-last-move')
  expect(server.sent.filter(m => m.type === 'GAME_ACTION_SEND')).toHaveLength(1)
  expect(errors).toEqual([])
  await expect(page.locator('vite-error-overlay')).toHaveCount(0)
})

test('M10 white player, stale rejection, timeout, recovery and draw retain the confirmed board', async ({ page }) => {
  const { server, panel } = await start(page, '102')
  await expect(panel).toContainText('내 돌: 백')
  const cell = panel.getByRole('button', { name: '1행 15열 빈칸', exact: true })
  server.rejectNextAction('GAME_ACTION_STALE_VERSION', '최신 판을 확인해주세요.')
  await cell.click()
  await expect(panel).toContainText('착수 반영 여부를 확인해야 합니다.')
  await expect(cell).toBeDisabled()
  await panel.getByRole('button', { name: '최신 판 확인' }).click()
  await expect(cell).toBeEnabled()
  server.dropActions(true)
  await cell.click()
  await expect(panel).toContainText('착수 요청 중')
  await expect(cell).toBeDisabled()
  await expect(panel).toContainText('응답 시간이 초과되었습니다.', { timeout: 12_000 })
  expect(server.sent.filter(m => m.type === 'GAME_ACTION_SEND')).toHaveLength(2)
  server.dropActions(false)
  await panel.getByRole('button', { name: '최신 판 확인' }).click()
  await expect(cell).toBeEnabled()
  await cell.click()
  await expect(panel).toContainText('마지막 수: 백 · 1행 15열')
  server.recoveryPending()
  await expect(panel.getByRole('button', { name: '1행 14열 빈칸', exact: true })).toBeDisabled()
  server.restoreGame()
  await expect(panel).toContainText('마지막 수: 백 · 1행 15열')
  server.finishGame('BOARD_FULL', null)
  await expect(panel).toContainText('무승부')
  await expect(panel).toContainText('종료 사유: 빈 교차점 없음')
  await expect(panel.getByRole('button', { name: '1행 14열 빈칸', exact: true })).toHaveCount(0)
  server.resendGame()
  await expect(panel.getByText('무승부입니다', { exact: true })).toHaveCount(1)
  await page.setViewportSize({ width: 1000, height: 700 })
  await expect(panel).toBeInViewport()
  await expect(panel.getByRole('group', { name: '오목판', exact: true })).toHaveCount(0)
  await screenshot(page, 'm10-mobile-draw')
  expect(server.maxActive).toBe(1)
})

test('M10 expired deadline blocks input while only a server result can announce a loss', async ({ page }) => {
  const { server, panel } = await start(page)
  server.turnTo('101', new Date(Date.now() - 1000).toISOString())
  await expect(panel).toContainText('서버의 종료 판정을 기다리고 있습니다.')
  await expect(panel).not.toContainText('패배')
  await expect(panel.getByRole('button', { name: '8행 8열 빈칸', exact: true })).toBeDisabled()
  server.finishGame('TURN_TIMEOUT', '102')
  await expect(panel).toContainText('승리')
  await expect(panel).toContainText('종료 사유: 착수 시간 초과')
  expect(server.sent.some(m => m.type === 'GAME_ACTION_SEND')).toBe(false)
})
