import { expect, test, type Page } from '@playwright/test'
import { fixture, screenshot } from './contractFixture'

const wheel = (page: Page) => page.getByRole('dialog', { name: '감정표현 선택' })
async function probe(page: Page): Promise<ReturnType<typeof import('./sceneProbe').emoteProbe>> {
  return page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).emoteProbe())
}
async function loaded(page: Page) {
  await page.goto('/park')
  await expect(page).toHaveTitle('OnTop')
  await expect(page.getByLabel('공원 기본 화면')).toBeVisible()
  await expect(page.getByText('공원을 준비하고 있어요…')).toBeHidden({ timeout: 90_000 })
  await page.locator('canvas').focus()
}

test('M04 G hold/release, keyboard, cancellation and input ownership preserve movement/chat', async ({ page }) => {
  const errors: string[] = [], consoleErrors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') consoleErrors.push(message.text()) })
  const server = await fixture(page, { position: { x: 0, y: 0.8, z: 34, yaw: 0 } })
  await loaded(page)
  await page.mouse.move(900, 440)
  await page.keyboard.down('KeyG')
  await expect(wheel(page)).toBeVisible()
  expect(await wheel(page).locator('.emote-wheel-empty').count()).toBe(3)
  await screenshot(page, 'm04-wheel-desktop')
  const option = await wheel(page).getByRole('button', { name: '손 인사', exact: true }).boundingBox()
  await page.mouse.move(option!.x + option!.width / 2, option!.y + option!.height / 2)
  await page.keyboard.up('KeyG')
  await expect(wheel(page)).toBeHidden()
  await expect.poll(async () => (await probe(page)).avatars[0]!.emote).toBe('EMOTE_WAVE')
  expect(server.sent.filter(m => m.type === 'WORLD_EMOTE_SEND').map(m => m.payload)).toEqual([{ emoteCode: 'WAVE' }])
  const cooldown = (await probe(page)).readyAt
  await page.keyboard.down('KeyW')
  await expect.poll(() => server.sent.some(m => m.type === 'WORLD_MOVE' && Number(m.payload.dz) < 0)).toBe(true)
  await expect.poll(async () => (await probe(page)).avatars[0]!.emote).toBe('')
  await page.keyboard.up('KeyW')
  expect((await probe(page)).readyAt).toBe(cooldown)
  await page.getByRole('button', { name: '감정표현 열기' }).click()
  await expect(wheel(page).getByRole('button', { name: '박수', exact: true })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(wheel(page)).toBeHidden()
  const moves = server.sent.filter(m => m.type === 'WORLD_MOVE' && (m.payload.dx || m.payload.dz)).length
  await page.keyboard.press('Enter')
  await page.getByLabel('주변 채팅 메시지').fill('g 키 입력')
  await page.keyboard.press('KeyG')
  await expect(wheel(page)).toBeHidden()
  expect(server.sent.filter(m => m.type === 'WORLD_MOVE' && (m.payload.dx || m.payload.dz))).toHaveLength(moves)
  await page.keyboard.press('Escape')
  await page.locator('canvas').focus()
  await page.keyboard.down('KeyG')
  await expect(wheel(page)).toBeVisible()
  await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  await expect(wheel(page)).toBeHidden()
  await page.keyboard.up('KeyG')
  expect(server.sent.filter(m => m.type === 'WORLD_EMOTE_SEND')).toHaveLength(1)
  await page.getByRole('button', { name: '감정표현 열기' }).click()
  await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).fixtureInputFlag('mapOpen', true))
  await expect(wheel(page)).toBeHidden()
  await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).fixtureInputFlag('mapOpen', false))
  await page.waitForTimeout(Math.max(0, cooldown - Date.now()) + 100)
  await page.getByRole('button', { name: '감정표현 열기' }).click()
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('Enter') // first slot, explicitly labelled local mock
  await expect.poll(async () => (await probe(page)).avatars[0]!.emote).toBe('EMOTE_APPLAUSE_REQUEST')
  await expect(page.getByRole('status')).toContainText('이 화면에서만 표시')
  expect(server.sent.filter(m => m.type === 'WORLD_EMOTE_SEND')).toHaveLength(1)
  expect(await page.locator('vite-error-overlay').count()).toBe(0)
  expect(errors).toEqual([])
  expect(consoleErrors).toEqual([])
})

test('M04 uses one approved timestamp in two viewers, never replays a duplicate or a reconnect', async ({ page, context }) => {
  const a = await fixture(page, { manualMovement: true, position: { x: 0, y: 0.8, z: 34, yaw: 0 } })
  await loaded(page)
  const observer = await context.newPage()
  const b = await fixture(observer, { manualMovement: true, ownUserId: '102', position: { x: 0, y: 0.8, z: 34, yaw: 0 } })
  await loaded(observer)
  a.emoteResponse('hold')
  await page.getByRole('button', { name: '감정표현 열기' }).click()
  await wheel(page).getByRole('button', { name: '박수', exact: true }).click()
  await expect.poll(async () => (await probe(page)).pending).toBe(true)
  expect((await probe(page)).avatars[0]!.emote).toBe('')
  await page.waitForTimeout(250)
  a.completeEmote()
  const event = a.lastEmote()!
  b.emote(event)
  await expect.poll(async () => (await probe(page)).avatars[0]!.at).toBe(Date.parse(event.sentAt))
  await expect.poll(async () => (await probe(observer)).avatars[0]!.at).toBe(Date.parse(event.sentAt))
  b.emote({ ...event, eventId: 'older', sentAt: new Date(Date.parse(event.sentAt) - 500).toISOString() })
  b.emote(event)
  expect((await probe(observer)).avatars[0]!.at).toBe(Date.parse(event.sentAt))
  await screenshot(page, 'm04-approved-clap')
  b.close(1012)
  await expect.poll(() => b.connections, { timeout: 15_000 }).toBe(2)
  b.emote(event)
  expect((await probe(observer)).avatars[0]!.emote).toBe('')
  expect(b.sent.filter(m => m.type === 'WORLD_EMOTE_SEND')).toHaveLength(0)
  await observer.close()
})

test('M04 click/mobile supports visible mock labels and server rejection never becomes a local success', async ({ page }) => {
  const server = await fixture(page, { manualMovement: true })
  await loaded(page)
  server.emoteResponse('reject')
  await page.getByRole('button', { name: '감정표현 열기' }).click()
  await wheel(page).getByRole('button', { name: '박수', exact: true }).click()
  await expect(page.locator('.emotes').getByRole('alert')).toContainText('등록되지 않은 감정표현')
  expect((await probe(page)).avatars[0]!.emote).toBe('')
  expect((await probe(page)).readyAt).toBe(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '감정표현 열기' }).click()
  const box = await wheel(page).boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(390)
  await expect(wheel(page).getByRole('button', { name: '방귀 뿡', exact: true })).toContainText('목업')
  await screenshot(page, 'm04-wheel-mobile')
  await wheel(page).getByRole('button', { name: '방귀 뿡', exact: true }).click()
  await expect.poll(async () => (await probe(page)).avatars[0]!.emote).toBe('EMOTE_FART')
  expect(server.sent.filter(m => m.type === 'WORLD_EMOTE_SEND')).toHaveLength(1)
  await page.getByRole('button', { name: '감정표현 열기' }).click()
  server.close(1012)
  await expect(wheel(page)).toBeHidden()
  await expect.poll(async () => (await probe(page)).wheelOpen).toBe(false)
})

test('M04 keeps unmapped server expressions unavailable and does not reopen over a table panel', async ({ page }) => {
  const server = await fixture(page, { emoteBindings: false, manualMovement: true })
  await loaded(page)
  await page.getByRole('button', { name: '감정표현 열기' }).click()
  for (const label of ['손 인사', '박수']) {
    const option = wheel(page).getByRole('button', { name: label, exact: true })
    await expect(option).toBeDisabled()
    await expect(option).toContainText('미연결')
  }
  await expect(wheel(page).getByRole('button', { name: '방귀 뿡', exact: true })).toContainText('목업')
  await page.keyboard.press('Escape')
  await page.evaluate(async () => {
    const { parkRuntime } = await import('/src/park/runtime/runtime.ts' as string)
    await parkRuntime.sendEmote('EMOTE_CLAP')
  })
  expect(server.sent.some(message => message.type === 'WORLD_EMOTE_SEND')).toBe(false)
  expect((await probe(page)).avatars[0]!.emote).toBe('')
  await page.evaluate(async () => {
    const { useSession } = await import('/src/network/worldClient.ts' as string)
    useSession.setState({ focusedAnchorId: 'table-1' })
  })
  await expect(page.getByRole('button', { name: '감정표현 열기' })).toBeHidden()
  await page.locator('canvas').focus()
  await page.keyboard.press('KeyG')
  await expect(wheel(page)).toBeHidden()
})
