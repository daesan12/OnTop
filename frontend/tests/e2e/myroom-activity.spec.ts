import { expect, test } from '@playwright/test'
import { fixture } from './contractFixture'

test('마이룸 열기·닫기·Esc는 공개 상태와 함께 바뀌고 상대 머리 위에도 표시한다', async ({ page }, info) => {
  const server = await fixture(page, { manualMovement: true, position: { x: 0, y: .8, z: 34, yaw: 0 } })
  await page.route('**/api/v1/users/me/items', route => route.fulfill({ json: { items: [] } }))
  await page.route('**/api/v1/wallets/me', route => route.fulfill({ json: { balance: 1000, reservedBalance: 0, availableBalance: 1000 } }))
  await page.goto('/park')
  await expect.poll(() => page.evaluate(async () => {
    const s = (await import('/src/network/worldClient.ts' as string)).useSession.getState()
    return s.status === 'connected' && s.ids.includes('102')
  }), { timeout: 90000 }).toBe(true)
  await expect(page.getByText('공원을 준비하고 있어요…')).toBeHidden({ timeout: 90000 })
  const own = page.locator('.avatar-overhead[data-player-id="101"] .avatar-activity')
  const changes = () => server.sent.filter(s => s.type === 'WORLD_MYROOM_SET').map(s => s.payload.open)
  await page.getByRole('button', { name: '옷장', exact: true }).click()
  await expect(own).toHaveText('마이룸 사용 중')
  await expect.poll(changes).toEqual([true])
  await page.getByRole('button', { name: '옷장 닫기', exact: true }).click()
  await expect(own).toHaveCount(0)
  await expect.poll(changes).toEqual([true, false])
  await page.getByRole('button', { name: '옷장', exact: true }).click()
  await expect(own).toHaveText('마이룸 사용 중')
  await page.keyboard.press('Escape')
  await expect(own).toHaveCount(0)
  await expect.poll(changes).toEqual([true, false, true, false])
  server.remotePose({ x: 2, y: .8, z: 32, yaw: 0 })
  server.activity('102', 'MYROOM')
  const other = page.locator('.avatar-overhead[data-player-id="102"]')
  await expect(other.locator('.avatar-activity')).toBeVisible()
  await expect(other.locator('.avatar-activity')).toHaveText('마이룸 사용 중')
  server.chatFrom('102', '옷 고르는 중이에요')
  await expect(other.getByText('옷 고르는 중이에요', { exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath('myroom-overhead.png') })
  server.activity('102', null)
  await expect(other.locator('.avatar-activity')).toHaveCount(0)
})
