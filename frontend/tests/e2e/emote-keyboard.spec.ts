import { expect, test, type Page } from '@playwright/test'
import { fixture, screenshot } from './contractFixture'

async function loaded(page: Page) {
  await page.goto('/park')
  await expect(page.getByLabel('공원 기본 화면')).toBeVisible({ timeout: 90_000 })
  await expect(page.locator('.avatar-overhead').first()).toBeAttached({ timeout: 90_000 })
  await expect.poll(() => page.evaluate(async () => (await import('/src/features/follow/state.ts' as string)).useFollow.getState().ready)).toBe(true)
}
async function wheel(page: Page) {
  await page.keyboard.down('KeyG')
  await expect(page.getByRole('dialog', { name: '감정표현 선택' })).toBeVisible()
  await page.keyboard.press('Escape'); await page.keyboard.up('KeyG')
}

test('G survives follow start and stop, including focus on the follow status button', async ({ page }) => {
  const server = await fixture(page, { manualMovement: true, emoteBindings: 'development', position: { x: 0, y: .8, z: 34, yaw: 0 } })
  await loaded(page)
  server.remotePose({ x: 3, y: .8, z: 33 })
  await page.locator('canvas').focus()
  await page.evaluate(async () => (await import('/src/features/follow/FollowMenu.tsx' as string)).openAvatarMenu({ id: '102', x: 600, y: 300 }))
  await page.getByRole('menuitem', { name: '따라가기', exact: true }).click()
  await expect(page.getByRole('button', { name: '따라가기 종료', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '따라가기 종료', exact: true }).focus()
  await wheel(page)
  await page.getByRole('button', { name: '따라가기 종료', exact: true }).click()
  await expect(page.getByRole('button', { name: '따라가기 종료', exact: true })).toHaveCount(0)
  await wheel(page)
  await page.getByRole('button', { name: '감정표현 열기' }).click()
  await page.getByRole('button', { name: /방귀 뿡/ }).click()
  await expect.poll(() => server.sent.some(m => m.type === 'WORLD_EMOTE_SEND' && m.payload.emoteCode === 'FART')).toBe(true)
  await screenshot(page, 'g-after-follow-start-stop')
})

test('G works after closed account and profile menus but stays blocked while editing or a menu is open', async ({ page }) => {
  await page.setViewportSize({ width: 1366, height: 768 })
  await fixture(page, { emoteBindings: 'development' }); await loaded(page)
  const account = page.getByRole('button', { name: '내 메뉴', exact: true })
  await account.click()
  await page.keyboard.down('KeyG')
  await expect(page.getByRole('dialog', { name: '감정표현 선택' })).toHaveCount(0)
  await page.keyboard.up('KeyG'); await page.keyboard.press('Escape')
  await expect(account).toBeFocused()
  await wheel(page)
  await account.click(); await page.getByRole('menuitem', { name: /내 정보/ }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('KeyG')
  await expect(page.getByRole('dialog', { name: '감정표현 선택' })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await wheel(page)
  await page.getByRole('button', { name: '채팅 입력창 열기', exact: true }).click()
  await page.keyboard.press('KeyG')
  await expect(page.getByRole('dialog', { name: '감정표현 선택' })).toHaveCount(0)
  await page.keyboard.press('Escape'); await wheel(page)
  await page.keyboard.press('F1')
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('KeyG')
  await expect(page.getByRole('dialog', { name: '감정표현 선택' })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await wheel(page)
  await page.keyboard.press('KeyM')
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('KeyG')
  await expect(page.getByRole('dialog', { name: '감정표현 선택' })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await wheel(page)
})
