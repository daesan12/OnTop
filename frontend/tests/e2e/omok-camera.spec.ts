import { expect, test, type Page } from '@playwright/test'
import { fixture, screenshot } from './contractFixture'

const probe = (page: Page) => page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).omokCameraProbe())
const ready = (page: Page) => expect.poll(async () => (await probe(page)).ready).toBe(true)

for (const own of ['101', '102'] as const) test(`original omok camera: seat ${own} scaling, orientation, transitions and authority`, async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  const server = await fixture(page, { omok: true, ownUserId: own })
  await page.setViewportSize({ width: 1280, height: 720 })
  await page.goto('/park')
  await expect(page).toHaveTitle(/온탑|OnTop/i)
  await expect(page.getByText('공원을 준비하고 있어요…')).toBeHidden({ timeout: 90_000 })
  await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).inspectTable())
  await page.getByRole('button', { name: '앉기', exact: true }).click()
  if (own === '102') server.host(own)
  await page.getByRole('button', { name: '오목 선택', exact: true }).click()
  await page.getByRole('button', { name: '준비', exact: true }).click()
  server.confirmStart(); server.turnTo(own)
  const panel = page.getByRole('region', { name: '오목 경기', exact: true })
  await expect(panel).toContainText('내 차례')
  await ready(page)
  for (const viewport of [{ width: 1280, height: 720 }, { width: 1920, height: 1080 }, { width: 1000, height: 1400 }]) {
    await page.setViewportSize(viewport)
    await expect.poll(async () => (await probe(page)).viewport).toEqual([viewport.width, viewport.height])
    await ready(page)
    const state = await probe(page), [a, b, c] = state.corners as [number[], number[], number[]]
    expect(Math.abs(b[0]! - a[0]!) / Math.min(...state.viewport)).toBeCloseTo(.8, 2)
    expect(Math.abs(c[1]! - b[1]!) / Math.min(...state.viewport)).toBeCloseTo(.8, 2)
    expect(Math.sign(b[0]! - a[0]!)).toBe(own === '101' ? 1 : -1)
    expect(Math.sign(c[1]! - b[1]!)).toBe(own === '101' ? 1 : -1)
    expect(state.direction[1]).toBeCloseTo(-1, 5)
    expect(state.fov).toBeCloseTo(42, 1)
    expect(state).toMatchObject({ layers: 2, rayLayers: 2, backdrop: true, backdropTriangles: 2 })
    for (const corner of state.corners) {
      expect(corner[0]).toBeGreaterThan(0); expect(corner[0]).toBeLessThan(viewport.width)
      expect(corner[1]).toBeGreaterThan(0); expect(corner[1]).toBeLessThan(viewport.height)
    }
    await screenshot(page, `omok-camera-${own}-${viewport.width}`)
  }
  await page.setViewportSize({ width: 1280, height: 720 }); await ready(page)
  await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).startOmokCameraTrace())
  server.turnTo(own === '101' ? '102' : '101')
  await expect(panel).toContainText('상대 차례')
  await expect.poll(async () => (await probe(page)).fov).toBeCloseTo(76, 1)
  const frames: { fov: number; ready: boolean }[] = await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).finishOmokCameraTrace())
  expect(frames.some(f => f.fov > 43 && f.fov < 75)).toBe(true)
  expect(frames.some(f => !f.ready)).toBe(true)
  expect((await probe(page)).layers).toBe(1)
  expect(server.sent.filter(message => message.type === 'GAME_ACTION_SEND')).toHaveLength(0)
  await screenshot(page, `omok-camera-${own}-opponent`)
  server.turnTo(own); await ready(page)
  await panel.getByRole('button', { name: '주변 둘러보기', exact: true }).click()
  await expect.poll(async () => (await probe(page)).ready).toBe(false)
  await expect.poll(async () => (await probe(page)).fov).toBeCloseTo(76, 1)
  expect((await probe(page)).backdrop).toBe(false)
  await panel.getByRole('button', { name: '판으로 돌아가기', exact: true }).click()
  expect((await probe(page)).ready).toBe(false)
  const movingPoint = await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).pointForOmok(3, 4))
  await page.mouse.click(movingPoint.x, movingPoint.y)
  expect(server.sent.filter(message => message.type === 'GAME_ACTION_SEND')).toHaveLength(0)
  await ready(page)
  // Actual ray picks must preserve server coordinates even with the opposite seat's 180° view.
  const point = await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).pointForOmok(3, 4))
  await page.mouse.click(point.x, point.y)
  await expect.poll(() => server.sent.filter(message => message.type === 'GAME_ACTION_SEND').length).toBe(1)
  expect(server.sent.find(message => message.type === 'GAME_ACTION_SEND')?.payload.input).toEqual({ x: 3, y: 4 })
  server.finishGame()
  await expect(page.locator('.gathering-hud')).toContainText('경기 결과')
  await expect.poll(async () => (await probe(page)).fov).toBeCloseTo(60, 1)
  expect(await probe(page)).toMatchObject({ ready: false, layers: 1, rayLayers: 1, backdrop: false })
  await page.getByRole('button', { name: '정산 결과 확인', exact: true }).click()
  server.settle(); server.nextRound()
  await page.getByRole('button', { name: '다음 판 준비', exact: true }).click()
  await page.getByRole('button', { name: /^(자리에서 )?일어나기$/ }).click()
  await expect(page.locator('.gathering-hud')).toHaveCount(0)
  expect(server.connections).toBe(1); expect(server.maxActive).toBe(1)
  expect(errors).toEqual([])
  await expect(page.locator('vite-error-overlay')).toHaveCount(0)
})
