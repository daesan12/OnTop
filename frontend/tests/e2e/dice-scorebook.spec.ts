import { expect, test, type Page } from '@playwright/test'
import { fixture, screenshot } from './contractFixture'
const panel = (page: Page) => page.getByRole('region', { name: '주사위 경기', exact: true })
const probe = (page: Page) => page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).farkleProbe())
const values = (faces: number[]) => faces.map((value, id) => ({ id, value, held: false }))
async function clickObject(page: Page, name: string) {
  const point = await page.evaluate(async name => (await import('/tests/e2e/sceneProbe.ts' as string)).pointForFarkleObject(name), name)
  await page.mouse.click(point.x, point.y)
}
async function start(page: Page, own: '101' | '102') {
  const server = await fixture(page, { omok: true, dice: true, m09: true, ownUserId: own })
  await page.goto('/park'); await expect(page).toHaveTitle('OnTop')
  await expect(page.getByText('공원을 준비하고 있어요…')).toBeHidden({ timeout: 90000 })
  await expect.poll(() => page.evaluate(async () => (await import('/src/network/worldClient.ts' as string)).useSession.getState().tables.length)).toBeGreaterThan(0)
  await page.evaluate(async () => (await import('/src/park/runtime/runtime.ts' as string)).parkRuntime.inspectTable('table-1'))
  await page.getByRole('button', { name: '앉기', exact: true }).click()
  if (own === '102') server.host(own)
  await page.getByLabel('1인 참가비', { exact: true }).fill('1')
  await page.getByRole('button', { name: '주사위 한 판 선택', exact: true }).click()
  await page.getByRole('button', { name: '준비', exact: true }).click(); server.confirmStart()
  server.diceSnapshot({ turnUserId: own, turnDeadline: new Date(Date.now() + 30000).toISOString() })
  await expect(panel(page)).toContainText('내 차례')
  await expect.poll(async () => (await probe(page)).cameraReady).toBe(true)
  return server
}

for (const own of ['101', '102'] as const) test(`scorebook pips, raycasts, timer and one flip per turn, seat ${own}`, async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  const server = await start(page, own)
  expect((await probe(page)).tabletopScale).toBe(.7)
  await expect.poll(async () => (await probe(page)).hourglass !== null).toBe(true)
  // Seat 102 is assigned after the fixture's initial 101 snapshot: that is a real presentation turn change.
  const initialFlips = (await probe(page)).hourglass!.flips
  await expect(page.getByLabel('주변 채팅', { exact: true })).toBeVisible()
  server.diceReply({ kind: 'roll', selectedIds: [] }, { dice: values([1, 1, 1, 5, 3, 2]), stage: 'SELECTING', rollId: 1, lastEvent: 'ROLL', turnScore: 500 })
  if (own === '102') {
    const point = await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).pointForFarkleCup())
    await page.mouse.move(point.x, point.y); await page.mouse.down()
    await page.mouse.move(point.x - 70, point.y, { steps: 6 }); await page.mouse.move(point.x + 20, point.y, { steps: 6 })
    await expect(panel(page)).toContainText('컵을 놓으면 굴립니다.')
    await page.mouse.up()
  } else await panel(page).getByRole('button', { name: 'R 굴리기', exact: true }).click()
  await expect(panel(page).getByRole('button', { name: '주사위 1: 1', exact: true })).toBeEnabled()
  for (const id of [0, 1, 2, 3]) await clickObject(page, `farkle-die-${id}`)
  await expect(panel(page).getByRole('button', { name: 'Q 점수 챙기기 · 1,550점', exact: true })).toBeEnabled()
  await screenshot(page, `dice-compact-${own}`)
  const deadline = await page.evaluate(async () => (await import('/src/game/store.ts' as string)).useGame.getState().game?.dice?.turnDeadline)
  await clickObject(page, 'farkle-scorebook-prop')
  const sheet = page.getByRole('dialog', { name: '주사위 점수표', exact: true })
  await expect(sheet).toBeVisible()
  const sheetBox = await sheet.boundingBox()
  for (const name of ['farkle-die-0', 'farkle-die-3', 'farkle-hourglass']) {
    const point = await page.evaluate(async name => (await import('/tests/e2e/sceneProbe.ts' as string)).pointForFarkleObject(name), name)
    expect(point.x).toBeGreaterThan(sheetBox!.x + sheetBox!.width)
  }
  await expect(page.getByLabel('주변 채팅', { exact: true })).toBeHidden()
  await expect(sheet.getByRole('button', { name: '점수표 닫기', exact: true })).toBeFocused()
  await expect(sheet.locator('[data-rule=triple-1]')).toHaveAttribute('data-selected', 'true')
  await expect(sheet.locator('[data-rule=single-5]')).toHaveAttribute('data-selected', 'true')
  for (const [rule, faces] of [['straight-1-5', [1, 2, 3, 4, 5]], ['straight-2-6', [2, 3, 4, 5, 6]], ['straight-1-6', [1, 2, 3, 4, 5, 6]]] as const) {
    const dice = sheet.locator(`[data-rule=${rule}] .dice-face`)
    await expect(dice).toHaveCount(faces.length)
    for (let i = 0; i < faces.length; i++) await expect(dice.nth(i).locator('circle[data-pip]')).toHaveCount(faces[i]!)
  }
  const actionCount = server.sent.filter(m => m.type === 'GAME_ACTION_SEND').length
  await page.keyboard.press('KeyR'); await page.keyboard.press('KeyQ'); await page.keyboard.press('Tab')
  await expect(sheet.getByRole('button', { name: '점수표 닫기', exact: true })).toBeFocused()
  expect(server.sent.filter(m => m.type === 'GAME_ACTION_SEND')).toHaveLength(actionCount)
  await expect.poll(async () => (await probe(page)).hourglass!.remaining).toBeLessThan(.95)
  expect(await page.evaluate(async () => (await import('/src/game/store.ts' as string)).useGame.getState().game?.dice?.turnDeadline)).toBe(deadline)
  await screenshot(page, `dice-scorebook-${own}`)
  await page.keyboard.press('KeyT'); await expect(sheet).toBeHidden()
  await expect(page.getByLabel('주변 채팅', { exact: true })).toBeVisible()
  await page.locator('canvas').first().focus(); await page.keyboard.press('KeyT'); await expect(sheet).toBeVisible()
  await page.keyboard.press('Escape'); await expect(sheet).toBeHidden()
  server.diceSnapshot({ rollId: 2 })
  await expect.poll(async () => (await probe(page)).hourglass?.flips).toBe(initialFlips)
  server.diceSnapshot({ turnUserId: own === '101' ? '102' : '101', round: 2, turnDeadline: new Date(Date.now() + 30000).toISOString() })
  await expect.poll(async () => (await probe(page)).hourglass?.flips).toBe(initialFlips + 1)
  await expect.poll(async () => (await probe(page)).hourglass?.flipping).toBe(false)
  expect((await probe(page)).hourglass!.angle).toBeCloseTo((initialFlips + 1) * Math.PI)
  server.diceSnapshot({ lastEvent: 'ROLL' })
  await expect.poll(async () => (await probe(page)).hourglass?.flips).toBe(initialFlips + 1)
  server.diceSnapshot({ turnUserId: own, round: 3, turnDeadline: new Date(Date.now() + 30000).toISOString() })
  await expect.poll(async () => (await probe(page)).hourglass?.flips).toBe(initialFlips + 2)
  await expect.poll(async () => (await probe(page)).cameraReady).toBe(true)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.locator('canvas').first().focus(); await page.keyboard.press('KeyT'); await expect(sheet).toBeVisible()
  expect(await sheet.locator('.scorebook-page').evaluate(element => getComputedStyle(element).animationName)).toBe('none')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(sheet.getByRole('button', { name: '점수표 닫기', exact: true })).toBeInViewport({ ratio: 1 })
  expect(await sheet.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
  await page.keyboard.press('Escape'); await expect(sheet).toBeHidden()
  await expect(page.getByLabel('주변 채팅', { exact: true })).toBeVisible()
  await expect(page.locator('vite-error-overlay')).toHaveCount(0)
  expect(errors).toEqual([])
})
