import { test, expect } from '@playwright/test'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'
import { fixture } from './contractFixture'

const directory = process.env.MOVEMENT_COMPARISON_DIR
test('compares own-avatar rendering before and after on identical Bullet input and delayed snapshots', async ({ page }) => {
  test.skip(!directory, 'Optional local comparison; requires the actual Bullet trace generated by the Java test.')
  const traces = JSON.parse(readFileSync(join(directory!, 'bullet-traces.json'), 'utf8'))
  const trace = traces.find((t: { scenario: string; oneWayMs: number }) => t.scenario === 'flat' && t.oneWayMs === 50)
  await fixture(page, { manualMovement: true, position: trace.initial })
  await page.goto('/park')
  await expect(page.getByLabel('공원 기본 화면')).toBeVisible()
  await expect(page.getByText('공원을 준비하고 있어요…')).toBeHidden({ timeout: 90_000 })
  const results = []
  for (const predicted of [false, true]) {
    const result = await page.evaluate(async ({ trace, predicted }) => {
      const wc = await import('/src/network/worldClient.ts' as string)
      const { localMovement } = await import('/src/network/localMovementPrediction.ts' as string)
      const { EXPECTED_MAP_VERSION } = await import('/src/config/mapVersion.ts' as string)
      const { renderedMovementPose } = await import('/tests/e2e/sceneProbe.ts' as string)
      const id = wc.useSession.getState().sessionId, channelId = wc.useSession.getState().roomId
      let version = predicted ? 200000 : 100000
      wc.avatars.clear()
      const receive = (state: typeof trace.initial) => wc.receive({ type: 'WORLD_STATE', requestId: null,
        payload: { channelId, version: ++version, mapVersion: EXPECTED_MAP_VERSION,
          avatars: [{ userId: id, position: state, ...(predicted ? { motion: state.motion } : {}) }] } })
      receive(trace.initial)
      if (predicted) { await localMovement.prepare(); if (!localMovement.ready) throw new Error('Prediction did not initialize') }
      await new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve())))
      const origin = performance.now(), samples: { at: number; x: number; y: number; z: number }[] = []
      let frame = 0, command = 0, firstInputAt: number | null = null, firstResponseMs: number | null = null
      await new Promise<void>(resolve => {
        const render = () => {
          const now = performance.now(), at = now - origin
          const rendered = renderedMovementPose()
          if (rendered) {
            samples.push({ at, ...rendered })
            if (firstInputAt !== null && firstResponseMs === null && Math.abs(rendered.x - trace.initial.x) > .01)
              firstResponseMs = now - firstInputAt
          }
          while (frame < trace.frames.length && trace.frames[frame].at <= at) receive(trace.frames[frame++].state)
          while (command < trace.commands.length && trace.commands[command].at <= at) {
            const input = trace.commands[command++]
            if (firstInputAt === null) firstInputAt = now
            if (predicted) { localMovement.intend(input.intent, now); localMovement.sentInput(input.seq, now) }
          }
          if (at >= 1800) resolve()
          else requestAnimationFrame(render)
        }
        requestAnimationFrame(render)
      })
      let caption = document.getElementById('movement-qa-caption')
      if (!caption) {
        caption = document.createElement('p'); caption.id = 'movement-qa-caption'
        caption.style.cssText = 'position:absolute;left:24px;bottom:24px;background:Canvas;color:CanvasText;padding:12px;z-index:10000'
        document.body.append(caption)
      }
      caption.textContent = '제어된 실브라우저 리플레이 · ' + (predicted ? '본인 예측 적용' : '기존 서버 좌표 보간')
        + ' · 첫 렌더 위치 반응 ' + Number(firstResponseMs).toFixed(1) + 'ms · 운영 측정 아님'
      return { predicted, firstResponseMs, samples, metrics: localMovement.metrics(),
        scope: 'Actual rendered Three.js avatar; warm local scene, actual Bullet trace with controlled 100ms RTT. Synthetic login/transport. Not a live-server or human-input benchmark.' }
    }, { trace, predicted })
    expect(result.firstResponseMs).not.toBeNull()
    results.push(result)
    mkdirSync(join(directory!, '..', 'screenshots'), { recursive: true })
    await page.screenshot({ path: join(directory!, '..', 'screenshots', predicted ? 'browser-after.png' : 'browser-before.png') })
  }
  writeFileSync(join(directory!, 'browser-comparison.json'), JSON.stringify({ results }, null, 2))
  expect(Number(results[1]!.firstResponseMs)).toBeLessThan(Number(results[0]!.firstResponseMs))
  console.log(results.map(r => ({ predicted: r.predicted, firstResponseMs: r.firstResponseMs })))
})
