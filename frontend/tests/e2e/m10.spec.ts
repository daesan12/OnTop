import { test, expect } from '@playwright/test'
import { fixture, screenshot, tableId } from './contractFixture'

test('M10 missing manual surrender is preview-only, cancellable and leaves existing WS game intact', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  const server = await fixture(page, { omok: true })
  await page.goto('/park')
  await expect(page.getByText('공원을 준비하고 있어요…')).toBeHidden({ timeout: 90_000 })
  await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).inspectTable())
  await page.getByRole('button', { name: '앉기', exact: true }).click()
  await page.getByRole('button', { name: '오목 선택', exact: true }).click()
  await page.getByRole('button', { name: '준비', exact: true }).click()
  server.confirmStart()
  const panel = page.getByRole('region', { name: '오목 경기', exact: true })
  const before = server.sent.length
  await panel.getByRole('button', { name: '기권 미리보기 (목업)', exact: true }).click()
  await expect(panel.getByRole('group', { name: '기권 미리보기 확인' })).toBeVisible()
  await panel.getByRole('button', { name: '계속 두기', exact: true }).click()
  await expect(panel.getByRole('group', { name: '기권 미리보기 확인' })).toHaveCount(0)
  await panel.getByRole('button', { name: '기권 미리보기 (목업)', exact: true }).click()
  await panel.getByRole('button', { name: '기권 확인 (목업)', exact: true }).click()
  await expect(panel).toContainText('기권 의사 확인 미리보기 완료 · 실제 경기는 계속됩니다.')
  await expect(panel).toContainText('내 차례 · 0수')
  await expect(panel.getByRole('button', { name: '8행 8열 빈칸', exact: true })).toBeEnabled()
  expect(server.sent.slice(before)).toEqual([])
  await screenshot(page, 'm10-surrender-preview')
  expect(errors).toEqual([])
})

test('M10 spectators render the same server last move and result without input or surrender authority', async ({ page }) => {
  const server = await fixture(page, { omok: true, m09: true })
  await page.goto('/park')
  await expect(page.getByText('공원을 준비하고 있어요…')).toBeHidden({ timeout: 90_000 })
  await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).inspectTable())
  const lobby = page.getByRole('dialog', { name: '테이블 정보', exact: true })
  await page.evaluate(async tableId => (await import('/tests/e2e/sceneProbe.ts' as string)).previewPublicMatch({ channelId: 'fixture-channel', tableId, gameId: 'fixture-confirmed-omok' }), tableId)
  await lobby.getByRole('button', { name: '미리보기 경기 참조 확인' }).click()
  await lobby.getByRole('button', { name: '경기 관전', exact: true }).click()
  const panel = page.getByRole('region', { name: '오목 경기', exact: true })
  server.turnTo('102'); server.opponentMove(); server.resendGame('SPECTATOR')
  await expect(panel).toContainText('마지막 수: 백 · 7행 7열')
  await expect(panel.getByRole('button', { name: '7행 7열 백돌', exact: true })).toHaveAttribute('aria-current', 'true')
  await expect(panel.getByRole('button', { name: '8행 8열 빈칸', exact: true })).toBeDisabled()
  await expect(panel.getByRole('button', { name: /기권/ })).toHaveCount(0)
  server.finishGame('FIVE_IN_ROW', '102'); server.resendGame('SPECTATOR')
  await expect(panel).toContainText('백 승리')
  await expect(panel).toContainText('종료 사유: 오목 완성')
  await expect(panel).not.toContainText('결과·정산 확인 전입니다.')
  await expect(page.getByText('서버 메시지 형식을 확인할 수 없습니다.', { exact: true })).toHaveCount(0)
  await screenshot(page, 'm10-spectator-result')
  expect(server.sent.some(m => m.type === 'GAME_ACTION_SEND' || m.type === 'GAME_RESULT_CHECK')).toBe(false)
})
