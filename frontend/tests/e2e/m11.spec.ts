import { test, expect } from '@playwright/test'
import { fixture, screenshot, tableId } from './contractFixture'
test('M11 public reference preview still uses existing DICE WS, public-only spectator eyes and no input', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  const server = await fixture(page, { omok: true, dice: true, m09: true })
  await page.goto('/park')
  await expect(page.getByText('공원을 준비하고 있어요…')).toBeHidden({ timeout: 90_000 })
  await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).inspectTable())
  await page.evaluate(async tableId => (await import('/tests/e2e/sceneProbe.ts' as string)).previewPublicMatch({ channelId: 'fixture-channel', tableId, gameId: 'fixture-confirmed-dice' }), tableId)
  await page.getByRole('button', { name: '미리보기 경기 참조 확인' }).click()
  await page.getByRole('button', { name: '경기 관전', exact: true }).click()
  const panel = page.getByRole('region', { name: '주사위 경기', exact: true })
  await expect(panel).toContainText('주사위 한 판 관전')
  server.diceSnapshot({ dice: [1, 2, 3, 4, 5, 6].map((value, id) => ({ id, value, held: false })), stage: 'SELECTING', rollId: 1, lastEvent: 'ROLL' }, 'SPECTATOR')
  await expect(panel.getByRole('button', { name: '주사위 1: 1', exact: true })).toBeDisabled()
  await expect(panel.getByRole('button', { name: /^R |^Q 점수 챙기기|기권|정산 결과/ })).toHaveCount(0)
  await page.keyboard.press('KeyR'); await page.keyboard.press('KeyQ')
  expect(server.sent.some(m => m.type === 'GAME_ACTION_SEND' || m.type === 'GAME_RESULT_CHECK')).toBe(false)
  await panel.getByRole('button', { name: '최신 주사위 확인' }).click()
  await expect(panel).toContainText('이번 턴 누적: 0점')
  await screenshot(page, 'm11-spectator')
  await panel.getByRole('button', { name: '테이블 둘러보기' }).click()
  await panel.getByRole('button', { name: '공개 판 보기' }).click()
  await panel.getByRole('button', { name: '관전 종료' }).click()
  await expect(panel).toHaveCount(0)
  expect(errors).toEqual([])
  await expect(page.getByText('서버 메시지 형식을 확인할 수 없습니다.', { exact: true })).toHaveCount(0)
})
