import { test, expect } from '@playwright/test'
import { fixture, screenshot } from './contractFixture'

test('explicit preview exercises real avatar right click, start/stop, one bounded rope and disposal without simulating movement', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
  const server = await fixture(page, { manualMovement: true, position: { x: 0, y: .8, z: 34, yaw: 0 } })
  await page.goto('/park'); await expect(page).toHaveTitle('OnTop')
  await expect(page.getByText('공원을 준비하고 있어요…')).toBeHidden({ timeout: 90000 })
  await page.locator('canvas').focus(); server.remotePose({ x: 3, y: .8, z: 33, yaw: 0 })
  const mode = await page.evaluate(async () => (await import('/src/features/follow/service.ts' as string)).followService.mode)
  expect(mode).toBe('preview')
  await expect.poll(async () => page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).followRenderProbe().vertices)).toBe(0)
  await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).measureFollowDraw())
  const before = await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).followRenderProbe())
  const ownBefore = await page.evaluate(async () => ({ ...(await import('/src/network/worldClient.ts' as string)).avatars.get('101')!.current }))
  await expect.poll(async () => page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).avatarMenuPoint('102').worldX)).toBe(3)
  const point = await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).avatarMenuPoint('102'))
  await page.mouse.click(point.x, point.y, { button: 'right' })
  const menu = page.getByRole('menu').filter({ hasText: '따라가기' }); await expect(menu).toBeVisible()
  await menu.getByRole('menuitem', { name: '따라가기', exact: true }).click()
  await expect(page.getByRole('complementary', { name: '따라가기 상태', exact: true })).toContainText('실제 자동 이동 없음')
  await expect.poll(async () => page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).followRenderProbe().vertices)).toBe(48)
  const after = await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).followRenderProbe())
  expect(after.capacity).toBe(768); expect(after.finite).toBe(true); expect(after.textured).toBe(false)
  expect(after.ownDraw).toEqual({ calls: 1, triangles: 16 })
  console.log('Follow render probe (WebGL2 Low, 1920x1080, 2 actors):', JSON.stringify({ before, after }))
  expect(await page.evaluate(async () => ({ ...(await import('/src/network/worldClient.ts' as string)).avatars.get('101')!.current }))).toEqual(ownBefore)
  expect(server.sent.filter(m => m.type === 'WORLD_MOVE' && (m.payload.dx || m.payload.dz || m.payload.jump))).toHaveLength(0)
  await screenshot(page, 'follow-preview-rope')
  await page.getByRole('button', { name: '따라가기 종료', exact: true }).click()
  await expect(page.getByRole('complementary', { name: '따라가기 상태', exact: true })).toHaveCount(0)
  await expect.poll(async () => page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).followRenderProbe().vertices)).toBe(0)
  await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).watchFollowResources())
  await page.route('**/api/v1/admin/me', route => route.fulfill({ json: { canRead: true, canGrant: false, canOperate: false } }))
  await page.route('**/api/v1/admin/feedback?*', route => route.fulfill({ json: { items: [], nextCursor: null } }))
  await page.evaluate(() => { history.pushState(null, '', '/admin/feedback'); window.dispatchEvent(new PopStateEvent('popstate')) })
  await expect(page.getByRole('heading', { name: '소리함 의견 조회', exact: true })).toBeVisible()
  expect(await page.evaluate(async () => (await import('/tests/e2e/sceneProbe.ts' as string)).followResourceProbe())).toEqual({ geometry: 1, material: 1 })
  await expect(page.locator('vite-error-overlay')).toHaveCount(0); expect(errors).toEqual([])
})
