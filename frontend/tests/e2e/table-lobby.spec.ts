import { test, expect, type Page } from '@playwright/test'
import { fixture, screenshot } from './contractFixture'

const lobby = (p: Page) => p.getByRole('dialog', { name: '테이블 정보', exact: true })
async function load(p: Page) {
  await p.goto('/park')
  await expect(p.getByText('공원을 준비하고 있어요…')).toBeHidden({ timeout: 90_000 })
  await p.locator('canvas').click({ position: { x: 80, y: 300 } })
  await p.keyboard.press('KeyE')
  await expect(lobby(p)).toBeVisible()
}

test('unready movement exit works without optional GAME_START_STATE, while ready and owned input stay protected', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  const server = await fixture(page, { omok: true, m09: true, startEvents: false })
  await load(page)
  for (const selected of [false, true]) {
    await lobby(page).getByRole('button', { name: '앉기', exact: true }).click()
    if (selected) {
      await lobby(page).getByRole('button', { name: '오목 선택', exact: true }).click()
      await lobby(page).getByRole('button', { name: '준비', exact: true }).click()
      await expect(lobby(page)).toContainText('준비·경기·정산 중 이동키로 퇴장하지 않습니다.')
      await lobby(page).getByRole('button', { name: '테이블 정보 닫기' }).click()
      await page.locator('canvas').focus()
      await page.keyboard.press('KeyW')
      expect(server.sent.filter(m => m.type === 'TABLE_LEAVE')).toHaveLength(1)
      await page.getByRole('button', { name: '테이블 로비 열기', exact: true }).click()
      await lobby(page).getByRole('button', { name: '준비 취소', exact: true }).click()
    }
    await expect(lobby(page)).toContainText('창을 닫고 이동키로 일어날 수 있어요.')
    await page.keyboard.press('KeyW') // Focus remains inside the dialog.
    expect(server.sent.filter(m => m.type === 'TABLE_LEAVE')).toHaveLength(selected ? 1 : 0)
    await lobby(page).getByRole('button', { name: '테이블 정보 닫기' }).click()
    await page.locator('canvas').focus()
    await page.keyboard.press('ShiftLeft')
    expect(server.sent.filter(m => m.type === 'TABLE_LEAVE')).toHaveLength(selected ? 1 : 0)
    await page.keyboard.press('KeyS')
    await expect.poll(() => server.sent.filter(m => m.type === 'TABLE_LEAVE').length).toBe(selected ? 2 : 1)
    if (!selected) {
      await screenshot(page, 'movement-exit-without-start-state')
      await page.keyboard.press('KeyE')
      await expect(lobby(page)).toBeVisible()
    }
  }
  expect(server.sent.some(m => /RESIGN|FORFEIT/.test(m.type))).toBe(false)
  expect(errors).toEqual([])
  expect(await page.locator('vite-error-overlay').count()).toBe(0)
})

test('M09 lobby uses server host, four seats and exact game/target commands; preserves explicit exit', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  const server = await fixture(page, { omok: true, m09: true })
  await load(page)
  await expect(lobby(page).getByRole('button', { name: '경기 관전', exact: true })).toBeDisabled()
  await expect(lobby(page)).toContainText('현재 확정된 진행 경기가 없습니다.')
  await lobby(page).getByRole('button', { name: '앉기', exact: true }).click()
  await expect(lobby(page).getByRole('listitem')).toHaveCount(4)
  await expect(lobby(page)).toContainText('방장 · 게임과 목표')
  await lobby(page).getByRole('button', { name: '원카드 선택', exact: true }).click()
  await expect(lobby(page).getByRole('listitem')).toHaveCount(4)
  await expect(lobby(page).getByRole('button', { name: '준비', exact: true })).toBeEnabled()
  await lobby(page).getByRole('button', { name: '거짓말 다리 건너기 선택', exact: true }).click()
  await expect(lobby(page).getByRole('button', { name: '준비', exact: true })).toBeEnabled()
  await lobby(page).getByLabel('주사위 목표 점수').selectOption('4000')
  await lobby(page).getByRole('button', { name: '주사위 한 판 선택', exact: true }).click()
  await expect(lobby(page).getByRole('listitem')).toHaveCount(2)
  expect(server.sent.filter(m => m.type === 'GAME_SELECT').at(-1)?.payload).toEqual({ gameCode: 'DICE', targetScore: 4000 })
  await lobby(page).getByLabel('주사위 목표 점수').selectOption('6000')
  await expect.poll(() => server.sent.filter(m => m.type === 'GAME_SELECT').at(-1)?.payload).toEqual({ gameCode: 'DICE', targetScore: 6000 })
  server.host('102')
  await expect(lobby(page).getByRole('button', { name: '오목 선택', exact: true })).toBeDisabled()
  server.host('101')
  await lobby(page).getByRole('button', { name: '오목 선택', exact: true }).click()
  await expect(lobby(page).getByRole('button', { name: '준비', exact: true })).toBeEnabled()
  await screenshot(page, 'm09-lobby')
  await page.setViewportSize({ width: 1000, height: 700 })
  await expect(lobby(page)).toBeInViewport()
  await expect(lobby(page).getByRole('button', { name: '일어나기', exact: true })).toBeInViewport()
  await screenshot(page, 'm09-lobby-mobile')
  await lobby(page).getByRole('button', { name: '일어나기', exact: true }).click()
  await expect(lobby(page).getByRole('button', { name: '앉기', exact: true })).toBeVisible()
  expect(server.maxActive).toBe(1)
  expect(errors).toEqual([])
})

test('M09 rejected table query is a failure, retry keeps real WS; late closed query cannot reopen a lobby', async ({ page }) => {
  const server = await fixture(page, { omok: true, m09: true })
  server.watchMode('reject'); await load(page)
  await expect(lobby(page).getByRole('alert')).toContainText('관전 범위')
  await expect(lobby(page).getByText('테이블 상태 확인 중', { exact: true })).toHaveCount(0)
  server.watchMode('normal')
  await lobby(page).getByRole('button', { name: '테이블 정보 다시 확인' }).click()
  await expect(lobby(page).getByRole('listitem')).toHaveCount(4)
  await lobby(page).getByRole('button', { name: '테이블 정보 닫기' }).click()
  await expect.poll(() => server.sent.filter(m => m.type === 'TABLE_UNWATCH').length).toBe(1)
  server.watchMode('hold'); await page.locator('canvas').click({ position: { x: 80, y: 300 } }); await page.keyboard.press('KeyE')
  await expect(lobby(page).getByText('테이블 상태 확인 중', { exact: true })).toBeVisible()
  await lobby(page).getByRole('button', { name: '테이블 정보 닫기' }).click()
  server.replyWatch()
  await expect.poll(() => server.sent.filter(m => m.type === 'TABLE_UNWATCH').length).toBe(2)
  await expect(lobby(page)).toHaveCount(0)
})

test('M09 finished round keeps seats, settlement is server-owned; next-round control never fabricates a match', async ({ page }) => {
  const server = await fixture(page, { omok: true, m09: true })
  await load(page)
  await lobby(page).getByRole('button', { name: '앉기', exact: true }).click()
  await lobby(page).getByRole('button', { name: '오목 선택', exact: true }).click()
  await page.getByRole('button', { name: '준비', exact: true }).click()
  server.confirmStart(); server.finishGame()
  const board = page.getByRole('region', { name: '테이블 함께 보기', exact: true })
  await expect(board).toContainText('승리')
  await board.getByRole('button', { name: '정산 결과 확인' }).click()
  await expect(board).toContainText('정산 대기 중')
  expect(server.sent.filter(m => m.type === 'TABLE_LEAVE')).toHaveLength(0)
  server.settle(); server.nextRound()
  await expect(board).toContainText('정산 완료')
  await expect(board.getByRole('button', { name: '자리에서 일어나기', exact: true })).toBeEnabled()
  const before = server.sent.length
  await board.getByRole('button', { name: '다음 판 준비', exact: true }).click()
  await expect(lobby(page)).toBeVisible()
  await expect(lobby(page).getByRole('region', { name: '지난 판 결과' })).toHaveCount(0)
  expect(server.sent.slice(before).some(m => /START|READY|RESIGN|REMATCH/.test(m.type))).toBe(false)
  await screenshot(page, 'm09-next-round')
  await lobby(page).getByRole('button', { name: '테이블 정보 닫기' }).click()
  await page.locator('canvas').click({ position: { x: 80, y: 300 } }); await page.keyboard.press('KeyW')
  await expect.poll(() => server.sent.filter(m => m.type === 'TABLE_LEAVE').length).toBe(1)
  expect(server.sent.some(m => /RESIGN|FORFEIT/.test(m.type))).toBe(false)
})
