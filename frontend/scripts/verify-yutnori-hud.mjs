import { chromium, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
const output = process.env.YUT_QA_OUTPUT || path.join(tmpdir(), 'ontop-yutnori-hud-qa')
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: 'msedge', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1536, height: 1024 } })
  page.setDefaultTimeout(20000)
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.route('**/yut-park.html*', async route => {
    const response = await route.fetch()
    const html = (await response.text()).replace('id="root"', 'id="yut-hud-test"').replace('/src/game/yutnori/parkPreview.tsx', '/tests/fixtures/yutHud.tsx')
    await route.fulfill({ response, body: html })
  })
  await page.goto('http://127.0.0.1:5244/yut-park.html', { waitUntil: 'commit', timeout: 60000 })
  await expect(page.locator('.yut-board-3d')).toHaveAttribute('data-ready', 'true', { timeout: 90000 })
  await expect(page.locator('[data-node]')).toHaveCount(29)
  for (const [width, height] of [[1536, 1024], [1440, 960], [390, 844], [1024, 500]]) {
    await page.setViewportSize({ width, height }); await page.waitForTimeout(800)
    await expect(page.getByRole('button', { name: /^윷 던지기/ })).toBeInViewport()
    await expect(page.getByRole('group', { name: '모아 둔 이동권' })).toBeInViewport()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    for (const node of [5, 10, 15, 20, 23]) {
      const target = page.locator(`[data-node="${node}"]`)
      await expect(target).toBeInViewport()
      await (node === 20 ? page.locator('.yut-3d-piece-hit.yut-team-3') : node === 23 ? page.locator('.yut-3d-piece-hit.yut-team-2') : target).click({ trial: true })
    }
    await page.screenshot({ path: path.join(output, `hud-${width}x${height}.png`) })
    if (width < 1000 || height < 640) await page.locator('.yut-mobile-chat').click()
    await expect(page.getByLabel('전체 채팅 입력', { exact: true })).toBeInViewport()
    await page.getByLabel('전체 채팅 입력', { exact: true }).fill('전체 초안')
    await page.getByRole('button', { name: '팀', exact: true }).click()
    await page.getByLabel('팀 채팅 입력', { exact: true }).fill('팀 초안')
    await page.getByRole('button', { name: '전체', exact: true }).click()
    await expect(page.getByLabel('전체 채팅 입력', { exact: true })).toHaveValue('전체 초안')
    await page.getByRole('button', { name: '팀', exact: true }).click()
    await expect(page.getByLabel('팀 채팅 입력', { exact: true })).toHaveValue('팀 초안')
    await page.getByRole('button', { name: '전체', exact: true }).click()
    await page.screenshot({ path: path.join(output, `chat-${width}x${height}.png`) })
    if (width < 1000 || height < 640) await page.locator('.yut-chat-toggle').click()
  }
  await page.setViewportSize({ width: 1536, height: 1024 })
  await page.locator('.yut-piece-rack .yut-team-0').first().click()
  await expect(page.getByRole('button', { name: '기본 길 · 2칸 이동', exact: true })).toBeVisible()
  await page.locator('[data-node="3"]').click()
  await page.locator('.yut-game-menu summary').click()
  await expect(page.getByRole('button', { name: '설명서', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('.yut-game-menu details')).not.toHaveAttribute('open', '')
  expect(errors).toEqual([])
  await page.locator('.yut-board-3d canvas').evaluate(canvas => canvas.getContext('webgl2').getExtension('WEBGL_lose_context').loseContext())
  await expect(page.locator('.yut-board-fallback svg circle')).toHaveCount(29)
  await page.getByRole('button', { name: '10번 칸 핑 보내기', exact: true }).click()
  await page.screenshot({ path: path.join(output, 'hud-fallback.png') })
  await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(500)
  await expect(page.locator('.yut-board-fallback svg')).toBeInViewport()
  await page.getByRole('button', { name: '10번 칸 핑 보내기', exact: true }).click()
  await page.screenshot({ path: path.join(output, 'hud-fallback-mobile.png') })
  await page.setViewportSize({ width: 1536, height: 1024 })
  await page.goto('http://127.0.0.1:5244/yut-park.html?backdo=1', { waitUntil: 'commit' })
  await expect(page.locator('.yut-board-3d')).toHaveAttribute('data-ready', 'true')
  await page.getByRole('button', { name: /^윷 던지기/ }).click()
  await expect(page.locator('.yut-throw-view')).toHaveAttribute('data-expanded', 'true')
  await page.waitForTimeout(500)
  await page.screenshot({ path: path.join(output, 'hud-throw-air.png') })
  await expect(page.locator('.yut-throw-view')).toHaveAttribute('data-animating', 'false')
  await expect(page.locator('.yut-throw-caption')).toContainText('빽도 · 뒤로 1칸')
  await page.screenshot({ path: path.join(output, 'hud-backdo-expanded.png') })
  await expect(page.locator('.yut-throw-view')).toHaveAttribute('data-expanded', 'false')
  await page.screenshot({ path: path.join(output, 'hud-backdo-settled.png') })
  console.log(JSON.stringify({ pass: true, output, checks: ['native concept size', 'four teams', '29 node hits', 'mobile/low landscape', 'chat scope/drafts', 'move selection', 'menu Escape', 'WebGL fallback'] }))
} finally { await browser.close() }
