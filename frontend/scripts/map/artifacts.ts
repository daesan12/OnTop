export interface MapSource {path:string;sha256:string}
export interface MapArtifact {path:string;content:string}
export const SERVER_MAP_PATH='generated/park/server-map.json'
export const MANIFEST_PATH='generated/park/manifest.json'
export const FE_VERSION_PATH='src/map/park/generated/mapVersion.ts'
export const sha256=(text:string)=>createHash('sha256').update(text,'utf8').digest('hex')

/** Sorted object keys, meaningful array order, JSON numbers, no host paths or timestamps. */
export function canonicalJson(value:unknown):string {
  if(value===null||typeof value==='boolean'||typeof value==='string')return JSON.stringify(value)
  if(typeof value==='number') {
    if(!Number.isFinite(value))throw new Error('Map contains a non-finite number')
    return JSON.stringify(value)
  }
  if(Array.isArray(value))return '['+Array.from(value,v=>canonicalJson(v)).join(',')+']'
  if(typeof value==='object'&&Object.getPrototypeOf(value)===Object.prototype) {
    return '{'+Object.keys(value).sort().filter(k=>(value as Record<string,unknown>)[k]!==undefined).map(k=>JSON.stringify(k)+':'+canonicalJson((value as Record<string,unknown>)[k])).join(',')+'}'
  }
  throw new Error('Map must contain only plain JSON values')
}
const pretty=(value:unknown)=>JSON.stringify(JSON.parse(canonicalJson(value)),null,2)+'\n'
