export function createMapArtifacts(data:ParkMapData,inputSources:readonly MapSource[]) {
  if(data.metadata.schemaVersion!==2||data.metadata.stage!=='preview')throw new Error('Unsupported map schema/stage')
  const sources=inputSources.map(s=>({...s})).sort((a,b)=>a.path<b.path?-1:a.path>b.path?1:0)
  if(!sources.length||new Set(sources.map(s=>s.path)).size!==sources.length)throw new Error('Map source list is empty or duplicated')
  for(const s of sources)if(!/^src\/(map|config)\/.+\.ts$/.test(s.path)||s.path.includes('..')||s.path.includes('/generated/')||!/^([a-f0-9]{64})$/.test(s.sha256))throw new Error('Invalid map source: '+s.path)
  const hashes={dataHash:sha256(canonicalJson(data)),sourceHash:sha256(canonicalJson(sources))}
  const identity={format:'ontop.park-map',schemaVersion:data.metadata.schemaVersion,mapId:data.metadata.mapId,hashAlgorithm:'sha256',hashes,semantics}
  // The version hashes this identity; version and file checksums are not recursively hashed.
  const mapVersion=sha256(canonicalJson(identity))
  const server={...identity,mapVersion,data}
  const versionContent=`// Generated by pnpm map:generate. Do not edit.\n// Separate from the live service EXPECTED_MAP_VERSION until the new map is deployed.\nexport const PARK_MAP_ID=${JSON.stringify(data.metadata.mapId)} as const\nexport const PARK_MAP_SCHEMA_VERSION=${data.metadata.schemaVersion} as const\nexport const PARK_MAP_VERSION=${JSON.stringify(mapVersion)} as const\n`
  const artifacts:MapArtifact[]=[{path:SERVER_MAP_PATH,content:pretty(server)},{path:FE_VERSION_PATH,content:versionContent}]
  const counts={facilities:data.facilities.length,pavilions:data.pavilions.length,tables:data.tables.length,localSeats:data.tables.reduce((n,t)=>n+t.seatAnchors.length,0),obstacles:data.collision.obstacles.length,paths:data.paths.length,physicalBoxes:data.physics.boxes.length,physicalMeshes:data.physics.meshes.length,physicalHulls:data.physics.hulls.length,benches:data.interactions.benches.length,fitness:data.interactions.fitness.length,telescopes:data.interactions.telescopes.length}
  const manifest={format:'ontop.park-map-manifest',schemaVersion:data.metadata.schemaVersion,mapId:data.metadata.mapId,mapVersion,hashAlgorithm:'sha256',hashes,sources,counts,
    artifacts:artifacts.map(a=>({path:a.path,sha256:sha256(a.content),bytes:Buffer.byteLength(a.content,'utf8')})),
    validation:{definition:'passed',ids:'preserved',spawn:'walkable',backendIntegration:'pending',liveServiceVersion:'unchanged'},
  }
  artifacts.push({path:MANIFEST_PATH,content:pretty(manifest)})
  return {mapVersion,server,manifest,artifacts}
}
